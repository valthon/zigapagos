pub const Site = struct {
    /// Title of the website
    title: []const u8,
    /// URL where the website will be hosted.
    /// It must not contain a subpath.
    host_url: []const u8,
    /// Set this value if your website is hosted under a subpath of `host_url`.
    ///
    /// `host_url` and `url_prefix_path` are split to allow the development
    /// server to generate correct relative paths when serving the website
    /// locally.
    url_path_prefix: []const u8 = "",
    layouts_dir_path: []const u8,
    content_dir_path: []const u8,
    assets_dir_path: []const u8,
    /// Directory holding site-wide global data files (Ziggy `.ziggy` files).
    ///
    /// Each `<name>.ziggy` file is parsed once at build time and exposed to
    /// every layout as `$site.data('<name>')` (a Ziggy map). This is the
    /// Zigapagos equivalent of Astro's "content database" singleton
    /// (`getSite()` / a `main.json` read by every page): one source of truth,
    /// many consumers. The directory is optional — if it doesn't exist, no
    /// site data is loaded and `$site.data(...)` reports a missing-file error.
    data_dir_path: []const u8 = "data",
    /// Subpaths in `assets_dir_path` that will be installed unconditionally.
    /// All other assets will be installed only if referenced by a content file
    /// or a layout by calling `$site.asset('foo').link()`.
    ///
    /// Examples of incorrect usage of this field:
    /// - site-wide CSS files (should be `link`ed by templates)
    /// - RSS feeds (should be generated by defining `alternative` pages)
    ///
    /// Examples of correct usage of this field:
    /// - `favicon.ico` and other similar assets auto-discovered by browsers
    /// - `CNAME` (used by GitHub Pages when you set a custom domain)
    ///
    /// An entry may also be a `**` glob to install a whole subtree without
    /// enumerating every file (paths are relative to `assets_dir_path`):
    /// - `"**"` installs the entire assets directory (Astro's "copy public/")
    /// - `"img/**"` installs everything under `assets/img/`
    static_assets: []const []const u8 = &.{},
    /// When enabled, Zigapagos will automatically add 'width' and 'height'
    /// attributes to <img> elements for local assets.
    /// Be aware that setting 'width' and 'heigth' of an image will in some
    /// circumstances cause browsers to distort images.
    ///
    /// This problem can be solved by adding the following CSS code to your
    /// site:
    ///
    /// img {
    ///    height: auto;
    /// }
    image_size_attributes: bool = false,
    /// Which host's routing conventions the release-time SPA prerender pass
    /// (`src/spa.zig`) targets when writing `routing-manifest.json` files,
    /// and which host-config emitter (`runtime/scripts/emit-host-config.ts`)
    /// runs after the build. Must be one of "zigbase" (default, the
    /// first-party host), "nginx", or "apache" — enforced by `Config.validate`.
    deploy_target: []const u8 = "zigbase",
    /// When enabled, every site asset that is installed *because something
    /// linked it* is installed under a content-hashed filename instead of its
    /// verbatim one: `assets/style.css` → `/style.a1b2c3d4.css`, and every
    /// `$site.asset('style.css').link()` / `![](…)` reference resolves to that
    /// URL. See `src/fingerprint.zig` and issue #53.
    ///
    /// This is what lets a deploy set a far-future `Cache-Control` on the
    /// whole asset tree: a changed file is a changed URL, so a returning
    /// visitor can never be served a stale stylesheet against fresh HTML.
    ///
    /// Deliberately NOT fingerprinted, so the escape hatches still work:
    /// `static_assets` entries (`favicon.ico`, `CNAME`, `robots.txt` — things
    /// something *outside* the build looks up at a fixed path), build assets
    /// (their install path is yours to choose in `build.zig`), and page
    /// assets (installed next to the page that owns them).
    ///
    /// Release builds only. The in-memory live server — started by running
    /// `zigapagos` with NO subcommand; `zigapagos serve` is an error that
    /// points you at that, see `main.zig`'s `.serve` arm — always serves
    /// verbatim names, mirroring how it also skips the CSS minify pass. Dev
    /// serves what you wrote, release serves what you ship.
    ///
    /// Off by default: turning it on changes every linked asset's URL, which
    /// is a deploy-visible change no site should get without asking.
    asset_fingerprint: bool = false,
    /// When enabled, every heading that doesn't already carry an explicit
    /// `$heading.id(...)`/`$section.id(...)` gets a GitHub-compatible slug
    /// id injected automatically (`src/heading_slugs.zig`), so a same-page
    /// `#anchor` or cross-page `/page#anchor` link written against a doc's
    /// existing GitHub rendering keeps working without every heading
    /// needing a hand-written id. An explicit `$heading.id(...)`/
    /// `$section.id(...)` always wins and is never overwritten. Opt-in and
    /// off by default: existing sites that rely on "an unmatched anchor is a
    /// build error" keep that behaviour unless they turn this on.
    auto_heading_ids: bool = false,
};

pub const MultilingualSite = struct {
    /// URL where the website will be hosted.
    /// It must not contain a path other than '/'.
    host_url: []const u8,
    /// Directory that contains mappings from placeholders to translations,
    /// expressed as Ziggy files.
    ///
    /// Each Ziggy file must be named after the locale it's meant to offer
    /// translations for.
    i18n_dir_path: []const u8,
    layouts_dir_path: []const u8,
    assets_dir_path: []const u8,
    /// Location where site and build assets will be installed. By default
    /// assets will be installed directly in the output location.
    ///
    /// In mulitilingual websites Zigapagos will create a single copy of site
    /// assets which will then be installed at this location. It will be your
    /// duty to then copy this directory elsewhere if needed in your deployment
    /// setup (e.g. when deploying different localized variants to different
    /// hosts). Note that *page* assets will still be installed next to their
    /// relative page.
    assets_prefix_path: []const u8 = "",
    /// Subpaths in `assets_dir_path` that will be installed unconditionally.
    /// All other assets will be installed only if referenced by a content file
    /// or a layout by using `$site.asset('foo').link()`.
    ///
    /// Examples of incorrect usage of this field:
    /// - site-wide CSS files (should be `link`ed by templates)
    /// - RSS feeds (should be generated by defining `alternative` pages)
    ///
    /// Examples of correct usage of this field:
    /// - `favicon.ico` and other similar assets auto-discovered by browsers
    /// - `CNAME` (used by GitHub Pages when you set a custom domain)
    ///
    /// An entry may also be a `**` glob to install a whole subtree without
    /// enumerating every file (paths are relative to `assets_dir_path`):
    /// - `"**"` installs the entire assets directory (Astro's "copy public/")
    /// - `"img/**"` installs everything under `assets/img/`
    static_assets: []const []const u8 = &.{},
    /// Directory holding site-wide global data files (Ziggy `.ziggy` files),
    /// exposed to every layout as `$site.data('<name>')`. See the equivalent
    /// field on a single-locale `Site` for details. Optional.
    data_dir_path: []const u8 = "data",
    /// A list of locales of this website.
    ///
    /// For each entry the following values must be unique:
    ///   - `code`
    ///   - `output_prefix_override` (if set) + `host_url_override`
    locales: []const Locale,
    /// Content-hashed filenames for linked site assets. See the field of the
    /// same name on a single-locale `Site` for the full rationale and the
    /// exclusion list. Multilingual sites keep ONE copy of the site assets
    /// (installed under `assets_prefix_path`), so one fingerprint per asset
    /// covers every locale.
    asset_fingerprint: bool = false,
    /// When enabled, Zigapagos will automatically add 'width' and 'height'
    /// attributes to <img> elements for local assets.
    /// Be aware that setting 'width' and 'heigth' of an image will in some
    /// circumstances cause browsers to distort images.
    ///
    /// This problem can be solved by adding the following CSS code to your
    /// site:
    ///
    /// img {
    ///    height: auto;
    /// }
    image_size_attributes: bool = false,
    /// When enabled, every heading that doesn't already carry an explicit
    /// `$heading.id(...)`/`$section.id(...)` gets a GitHub-compatible slug
    /// id injected automatically (`src/heading_slugs.zig`), so a same-page
    /// `#anchor` or cross-page `/page#anchor` link written against a doc's
    /// existing GitHub rendering keeps working without every heading
    /// needing a hand-written id. An explicit `$heading.id(...)`/
    /// `$section.id(...)` always wins and is never overwritten. Opt-in and
    /// off by default: existing sites that rely on "an unmatched anchor is a
    /// build error" keep that behaviour unless they turn this on.
    auto_heading_ids: bool = false,
};

/// A localized variant of a multilingual website
pub const Locale = struct {
    /// A language-NATION code, e.g. 'en-US', used to identify each
    /// individual localized variant of the website.
    code: []const u8,
    /// A name that identifies this locale, e.g. 'English'
    name: []const u8,
    /// Content dir for this locale,
    content_dir_path: []const u8,
    /// Site title for this locale.
    site_title: []const u8,
    /// Set to a non-null value when deploying this locale from a dedicated
    /// host (e.g. 'https://us.site.com', 'http://de.site.com').
    ///
    /// It must not contain a path other than '/'.
    host_url_override: ?[]const u8 = null,
    /// |  output_ |     host_     |     resulting    |    resulting    |
    /// |  prefix_ |      url_     |        url       |      path       |
    /// | override |   override    |      prefix      |     prefix      |
    /// | -------- | ------------- | ---------------- | --------------- |
    /// |   null   |      null     | site.com/en-US/  | zig-out/en-US/  |
    /// |   null   | "us.site.com" | us.site.com/     | zig-out/en-US/  |
    /// |   "foo"  |      null     | site.com/foo/    | zig-out/foo/    |
    /// |   "foo"  | "us.site.com" | us.site.com/foo/ | zig-out/foo/    |
    /// |    ""    |      null     | site.com/        | zig-out/        |
    ///
    /// The last case is how you create a default locale.
    output_prefix_override: ?[]const u8 = null,
};

pub const Config = union(enum) {
    Multilingual: MultilingualSite,
    Site: Site,

    const config_file_basename = "zigapagos.ziggy";

    /// Returns the cfg and the the directory where the config file was
    /// found. The directory is then used by other code to place the output
    /// directory unless the user overrides that location from the CLI.
    pub fn load(io: Io, arena: Allocator) struct { Config, []const u8 } {
        errdefer |err| switch (err) {
            error.OutOfMemory => fatal.oom(),
        };

        const cwd_path = std.process.currentPathAlloc(io, arena) catch |err| {
            fatal.msg("error while trying to get the cwd path: {s}\n", .{
                @errorName(err),
            });
        };

        var base_dir_path: []const u8 = cwd_path;
        while (true) {
            const joined_path = try std.fs.path.join(arena, &.{
                base_dir_path, config_file_basename,
            });

            const data = Io.Dir.cwd().readFileAllocOptions(
                io,
                joined_path,
                arena,
                .limited(1024 * 1024),
                .of(u8),
                0,
            ) catch |err| switch (err) {
                error.FileNotFound => {
                    base_dir_path = std.fs.path.dirname(base_dir_path) orelse {
                        std.debug.print(
                            \\error: unable to find a 'zigapagos.ziggy' config file in this directory or any of its parents
                            \\
                            \\note: run `zigapagos init` in an empty directory to bootstrap a Zigapagos website
                            \\
                            \\
                            \\
                        , .{});

                        fatal.helpError();
                    };
                    continue;
                },
                else => fatal.file(joined_path, err),
            };

            // Named `cfg_diag`, not `diag` (the module import at the top of
            // this file), to avoid shadowing it -- this is a config-load
            // fatal, out of scope for this PR's code conversion (see
            // docs/diagnostics.md's scope section); it still reaches
            // `fatal.msg`, which handles the JSON branch on its own.
            var cfg_diag: ziggy.Diagnostic = .{ .path = joined_path };
            const cfg = ziggy.parseLeaky(Config, arena, data, .{
                .diagnostic = &cfg_diag,
                .copy_strings = .to_unescape,
            }) catch {
                fatal.msg(
                    \\Error while loading the Zigapagos config file:
                    \\
                    \\{f}
                    \\
                    \\
                , .{cfg_diag.fmt(data)});
            };

            cfg.validate();

            return .{ cfg, base_dir_path };
        }
    }

    pub fn validate(cfg: *const Config) void {
        switch (cfg.*) {
            .Site => |s| {
                const u = std.Uri.parse(s.host_url) catch |err| {
                    fatal.msg("error: host url '{s}' in zigapagos.ziggy is invalid: {s}", .{
                        s.host_url, @errorName(err),
                    });
                };

                if (!u.path.isEmpty()) blk: {
                    switch (u.path) {
                        .raw => {},
                        .percent_encoded => |p| {
                            if (std.mem.eql(u8, p, "/")) break :blk;
                        },
                    }
                    fatal.msg(
                        "error: 'host_url' in zigapagos.ziggy must not contain a path (but contains '{f}'), set 'url_path_prefix' instead",
                        .{std.fmt.alt(u.path, .formatPath)},
                    );
                }

                if (u.query) |q| fatal.msg(
                    "error: 'host_url' in zigapagos.ziggy must not contain a query (but contains '{f}')",
                    .{std.fmt.alt(q, .formatQuery)},
                );

                if (u.fragment) |f| fatal.msg(
                    "error: 'host_url' in zigapagos.ziggy must not contain a fragment (but contains '{f}')",
                    .{std.fmt.alt(f, .formatFragment)},
                );

                // `data_dir_path` belongs here like every other config directory:
                // Build.loadSiteData opens it with `base_dir.openDir(io, path, …)`,
                // and on POSIX `openat` ignores the dirfd for an ABSOLUTE path — so
                // without this, `data_dir_path = "/etc"` or "../../elsewhere/data"
                // read .ziggy files from outside the project and exposed them to
                // every layout via `$site.data(…)`, while the identical spelling in
                // content_dir_path was a fatal config error.
                const paths: []const []const u8 = &.{
                    s.content_dir_path,
                    s.assets_dir_path,
                    s.layouts_dir_path,
                    s.data_dir_path,
                };

                for (paths) |p| if (validatePathMessage(p, .{})) |msg| fatal.msg(
                    "error: path '{s}' in zigapagos.ziggy: {s}\n",
                    .{ p, msg },
                );

                if (validatePathMessage(
                    s.url_path_prefix,
                    .{ .empty = true },
                )) |msg| fatal.msg(
                    "error: url_path_prefix '{s}' in zigapagos.ziggy: {s}\n",
                    .{ s.url_path_prefix, msg },
                );

                const valid_deploy_targets: []const []const u8 = &.{ "zigbase", "nginx", "apache" };
                for (valid_deploy_targets) |t| {
                    if (std.mem.eql(u8, s.deploy_target, t)) break;
                } else fatal.msg(
                    "error: deploy_target '{s}' in zigapagos.ziggy is invalid, must be one of: zigbase, nginx, apache",
                    .{s.deploy_target},
                );
            },
            .Multilingual => |ml| {
                const u = std.Uri.parse(ml.host_url) catch |err| {
                    fatal.msg("error: host_url '{s}' in zigapagos.ziggy is invalid: {s}", .{
                        ml.host_url, @errorName(err),
                    });
                };

                if (!u.path.isEmpty()) blk: {
                    switch (u.path) {
                        .raw => {},
                        .percent_encoded => |p| {
                            if (std.mem.eql(u8, p, "/")) break :blk;
                        },
                    }
                    fatal.msg(
                        "error: host_url in zigapagos.ziggy must not contain a path (but contains '{f}'), set 'url_path_prefix' instead",
                        .{std.fmt.alt(u.path, .formatPath)},
                    );
                }

                if (u.query) |q| fatal.msg(
                    "error: host_url in zigapagos.ziggy must not contain a query (but contains '{f}')",
                    .{std.fmt.alt(q, .formatQuery)},
                );

                if (u.fragment) |f| fatal.msg(
                    "error: host_url in zigapagos.ziggy must not contain a fragment (but contains '{f}')",
                    .{std.fmt.alt(f, .formatFragment)},
                );

                const paths: []const []const u8 = &.{
                    ml.i18n_dir_path,
                    ml.assets_dir_path,
                    ml.layouts_dir_path,
                    // See the single-site array above for why data_dir_path must be
                    // validated with the rest.
                    ml.data_dir_path,
                };

                for (paths) |p| if (validatePathMessage(p, .{})) |msg| fatal.msg(
                    "error: path '{s}' in zigapagos.ziggy: {s}\n",
                    .{ p, msg },
                );

                for (ml.locales) |locale| {
                    if (locale.code.len == 0) fatal.msg(
                        "error: empty locale code found in zigapagos.ziggy",
                        .{},
                    );

                    if (validatePathMessage(
                        locale.content_dir_path,
                        .{},
                    )) |msg| fatal.msg(
                        "error: content_dir_path '{s}' in locale '{s}' in zigapagos.ziggy: {s}\n",
                        .{ locale.content_dir_path, locale.code, msg },
                    );

                    if (locale.host_url_override) |url| {
                        const lu = std.Uri.parse(url) catch |err| {
                            fatal.msg("error: host_url_override '{s}' in locale '{s}' in zigapagos.ziggy is invalid: {s}", .{
                                url, locale.code, @errorName(err),
                            });
                        };

                        if (!lu.path.isEmpty()) blk: {
                            switch (lu.path) {
                                .raw => {},
                                .percent_encoded => |p| {
                                    if (std.mem.eql(u8, p, "/")) break :blk;
                                },
                            }
                            fatal.msg(
                                "error: host_url_override in locale '{s}' in zigapagos.ziggy must not contain a path (but contains '{f}'), set 'url_path_prefix' instead",
                                .{
                                    locale.code,
                                    std.fmt.alt(u.path, .formatPath),
                                },
                            );
                        }

                        if (lu.query) |q| fatal.msg(
                            "error: host_url_override in locale '{s}' in zigapagos.ziggy must not contain a query (but contains '{f}')",
                            .{
                                locale.code,
                                std.fmt.alt(q, .formatQuery),
                            },
                        );

                        if (lu.fragment) |f| fatal.msg(
                            "error: host_url_override in locale '{s}' in zigapagos.ziggy must not contain a fragment (but contains '{f}')",
                            .{
                                locale.code,
                                std.fmt.alt(f, .formatFragment),
                            },
                        );
                    }

                    if (locale.output_prefix_override) |opo| {
                        if (validatePathMessage(opo, .{ .empty = true })) |msg| fatal.msg(
                            "error: output_prefix_override '{s}' in locale '{s}' in zigapagos.ziggy: {s}\n",
                            .{ opo, locale.code, msg },
                        );
                    }
                }
            },
        }
    }

    pub fn getLayoutsDirPath(c: *const Config) []const u8 {
        return switch (c.*) {
            .Site => |s| s.layouts_dir_path,
            .Multilingual => |m| m.layouts_dir_path,
        };
    }
    pub fn getAssetsDirPath(c: *const Config) []const u8 {
        return switch (c.*) {
            .Site => |s| s.assets_dir_path,
            .Multilingual => |m| m.assets_dir_path,
        };
    }

    pub fn getDataDirPath(c: *const Config) []const u8 {
        return switch (c.*) {
            .Site => |s| s.data_dir_path,
            .Multilingual => |m| m.data_dir_path,
        };
    }

    pub fn getStaticAssets(c: *const Config) []const []const u8 {
        return switch (c.*) {
            .Site => |s| s.static_assets,
            .Multilingual => |m| m.static_assets,
        };
    }

    /// `asset_fingerprint` (issue #53) — content-hashed filenames for linked
    /// site assets.
    pub fn getAssetFingerprint(c: *const Config) bool {
        return switch (c.*) {
            .Site => |s| s.asset_fingerprint,
            .Multilingual => |m| m.asset_fingerprint,
        };
    }

    /// The site's URL path prefix (empty when unset). Multilingual sites don't
    /// support one, so they always return "". Threaded into the dev loop so a
    /// hot-swap broadcast URL matches the prefixed `data-z-module` the SSR pass
    /// emits (see `islands/pass.zig`'s `prefixed`).
    pub fn getUrlPathPrefix(c: *const Config) []const u8 {
        return switch (c.*) {
            .Site => |s| s.url_path_prefix,
            .Multilingual => "",
        };
    }

    pub fn getImageAutosize(c: *const Config) bool {
        return switch (c.*) {
            .Site => |s| s.image_size_attributes,
            .Multilingual => |m| m.image_size_attributes,
        };
    }

    pub fn getAutoHeadingIds(c: *const Config) bool {
        return switch (c.*) {
            .Site => |s| s.auto_heading_ids,
            .Multilingual => |m| m.auto_heading_ids,
        };
    }

    pub fn getSiteTitle(c: *const Config, locale_id: u32) []const u8 {
        return switch (c.*) {
            .Site => |s| s.title,
            .Multilingual => |m| m.locales[locale_id].site_title,
        };
    }

    pub fn getHostUrl(c: *const Config, locale_id: ?u32) []const u8 {
        return switch (c.*) {
            .Site => |s| s.host_url,
            .Multilingual => |m| if (locale_id) |lid| m.locales[lid].host_url_override orelse m.host_url else m.host_url,
        };
    }

    /// The host's routing conventions targeted by `src/spa.zig`'s prerender
    /// pass. `Multilingual` sites don't (yet) support SPAs, so this always
    /// resolves to the "zigbase" default for them.
    pub fn deployTarget(self: *const Config) []const u8 {
        return switch (self.*) {
            .Site => |s| s.deploy_target,
            .Multilingual => "zigbase",
        };
    }
};

// Mirrors closely the corresponding type in build.zig
pub const BuildAsset = struct {
    input_path: []const u8,
    install_path: ?[]const u8 = null,
    install_always: bool = false,
    rc: std.atomic.Value(u32),
};

/// One `--spa=<src>|<base>` entry, as threaded from `build.zig`'s `Spa.src`/
/// `Spa.base` through `zigapagos release`'s CLI args. `base` is the DECLARED base
/// from the consumer's `build.zig` (used only for advisory purposes here);
/// `src/spa.zig`'s prerender pass treats the module's exported `spa.base` as
/// authoritative and asserts the two agree, failing loudly on mismatch. `base`
/// is `""` when the `--spa=` value carried no `|` (defensive fallback — the
/// agreement assert is skipped for that entry).
pub const SpaSpec = struct {
    src: []const u8,
    base: []const u8,
    /// Path to the driver's `spa-chunks.json` for this SPA (entry name + the
    /// lazy-route→chunk map), threaded via `zigapagos release --spa-chunks=<src>
    /// <path>`. Null when no chunk map was provided (e.g. a hand-written CLI
    /// invocation) — the prerender then emits no per-route chunk/preload.
    chunks_json: ?[]const u8 = null,
    /// Path to the driver's per-SPA runtime SLICE manifest (`build-spa-runtime.ts`),
    /// threaded via `zigapagos release --spa-slice=<src> <path>`. Either
    /// `{"runtime":"/spa/<name>-runtime.js","members":[…]}` (this SPA gets a
    /// sliced runtime bundle) or `{"fallback":true}` (uncertain host usage → the
    /// SPA uses the shared /zigapagos-runtime.js). Null for a hand-written CLI
    /// invocation with no slicing — the prerender then uses the shared runtime.
    slice_json: ?[]const u8 = null,
};

pub const Options = struct {
    build_assets: *const std.StringArrayHashMapUnmanaged(BuildAsset),
    base_dir_path: []const u8,
    mode: Mode,
    drafts: bool,
    bun_path: ?[]const u8 = null,
    island_sidecar: ?[]const u8 = null,
    island_src_dir: ?[]const u8 = null,
    /// Bun script that minifies each `.css` site asset during the disk-mode
    /// (release) install phase. When set (together with `bun_path`),
    /// `.css` assets from `assets_dir_path` are piped through it instead of being
    /// copied verbatim. Null — the default, and always the case for the in-memory
    /// live server — keeps the historical byte-for-byte copy, so the dev loop
    /// serves readable, un-mangled CSS (mirroring Vite: minify on build, not dev).
    css_minify_driver: ?[]const u8 = null,
    island_props_check: @import("islands/props_check.zig").Mode = .off,
    /// Path to the per-SITE islands runtime slice manifest, threaded through by
    /// `zigapagos release --islands-slice=<path>` (see
    /// `runtime/scripts/build-islands-runtime.ts`). Two shapes:
    /// `{"runtime":"/islands/_runtime.js","islands":[…]}` — a slice was built and
    /// covers those island modules — or `{"fallback":true}` — no island could be
    /// proved safe, so every island page keeps the shared runtime.
    /// Null (the default) means no slicing at all: every island page loads the
    /// shared runtime, the same PAGE OUTPUT a fallback manifest produces. It is
    /// not the same INVOCATION, though — a manifest-less run also skips the
    /// stale-slice prune below, deliberately; see the comment there.
    /// `zigapagos serve` never sets it: the live server serves
    /// `/zigapagos-runtime.js` from its own cache dir via a hard-coded route and
    /// never bundles a slice.
    islands_slice_json: ?[]const u8 = null,
    /// SPAs declared in `build.zig`'s `Options.spas`, threaded through by
    /// `zigapagos release --spa=<src>|<base>` (one per SPA). Consumed by
    /// `src/spa.zig`'s release-time prerender pass.
    spas: []const SpaSpec = &.{},
    /// Which SPA's "/" shell backs the universal 404.html, named
    /// by its `spaName(src)` basename and threaded through by `zigapagos
    /// release --spa-not-found=<name>`. Null (the default) keeps the
    /// historical behavior: the FIRST declared SPA. A name matching no
    /// declared SPA is a fatal build error (checked in `src/spa.zig`).
    spa_not_found: ?[]const u8 = null,
    /// Incremental content re-render (the `zigapagos dev` inner
    /// loop). When non-empty AND `mode == .disk`, each entry is a base-relative
    /// source path of a content page that changed (e.g. `content/blog/foo.md`).
    /// The render pass then re-renders + re-emits ONLY those pages, leaving the
    /// rest of the previously-built output tree untouched, and skips the SPA
    /// prerender + asset (re)install passes (nothing else changed). Empty (the
    /// default — every release build, and the dev loop's full-rebuild fallback)
    /// keeps the historical behavior: render + emit the whole site. Only the
    /// disk (release) build consults this; the in-memory live server ignores it.
    /// `zigapagos release` populates it from the `ZIGAPAGOS_CHANGED_FILES`
    /// environment variable, which `zigapagos dev` sets when — and only when —
    /// every file that changed is a content page (see `src/cli/dev.zig`).
    changed_files: []const []const u8 = &.{},
    /// Dev-only island-usage manifest (the `zigapagos dev` inner
    /// loop). When set (and `mode == .disk`), the render pass collects which
    /// islands each page mounts and writes the manifest
    /// (`src/islands/manifest.zig`) to this absolute path after rendering, so
    /// the dev loop can map an island-source edit to exactly the pages that
    /// need re-SSR. Null (the default — every ordinary release build) means
    /// nothing is collected or written: zero effect on release output.
    /// `zigapagos release` populates it from the `ZIGAPAGOS_ISLAND_MANIFEST`
    /// environment variable, which only `zigapagos dev` sets.
    island_manifest_path: ?[]const u8 = null,
    /// `--allow-missing-pages`: tolerate a `$link.page/sibling/sub` (content)
    /// or `$site.page(...)` (template) reference to a page that doesn't exist
    /// YET, instead of hard-failing the build. The TOLERANCE is deliberately
    /// uniform rather than mode-dependent (e.g. warn-in-dev,
    /// error-in-release): the workflow this exists for — an under-construction
    /// site with real navigation to not-yet-written pages, deployed
    /// continuously — needs `zigapagos release` (CI) to pass on the exact same
    /// input a green `dev` preview just showed, or dev/release parity breaks
    /// (a green preview, a red CI). A dangling internal link is what "under
    /// construction" means; the opt-in flag is the escape hatch, the build-log
    /// warning is the visibility mechanism. See issue #27 / DX-8. Off by
    /// default: an unintentionally-dangling link should still fail the build.
    ///
    /// Which CLI commands accept it: `zigapagos release` and the bundled live
    /// server (no subcommand) parse `--allow-missing-pages` directly. There is
    /// deliberately NO `zigapagos dev --allow-missing-pages`: `dev` never
    /// builds the site itself, it re-runs the consumer's rebuild command
    /// (default `zig build`), so the flag reaches a dev loop through that
    /// project's `build.zig` — `Options.allow_missing_pages` in `build/api.zig`,
    /// which `website()` forwards. A flag on `dev` would have nothing to
    /// forward it to.
    allow_missing_pages: bool = false,
    /// `zigapagos release --summary` (issue #42): print an inventory of the
    /// files this build emitted, grouped by category, once every pass has run.
    ///
    /// Read-only bookkeeping — collecting it cannot reorder or skip a pass, and
    /// the report prints after the asset-install phase, which must stay last.
    /// The two early returns below (`mode == .memory`, `incremental`) skip it
    /// for free and correctly: the live server emits no tree at all, and an
    /// incremental rebuild re-emits only the pages that changed, so an
    /// inventory of *this* run would read as if the rest of the site had
    /// vanished.
    summary: bool = false,
    /// The introspection commands (`zigapagos validate`, `zigapagos explain`)
    /// deliberately run a full in-memory build with NO island sidecar: their
    /// whole point is to check/report on content, layouts and links without
    /// the Bun toolchain, a build graph, or an output tree. Without this flag,
    /// worker.zig's renderPage treats "this page mounts an <island> but no
    /// sidecar is configured" as an authoring mistake and logs one error line
    /// PER island page -- correct for `release`/`dev`/the live server, where
    /// an unconfigured sidecar really is a missing `.islands` declaration in
    /// build.zig, and pure noise for a command that never asked for SSR
    /// (measured: 201 lines on a 201-page island fixture).
    ///
    /// When true, that branch stays silent and the raw `<island>` markup is
    /// left in `page._render.out` -- which is exactly what `explain` then
    /// tokenizes to enumerate a page's islands Bun-free.
    ///
    /// It suppresses a LOG LINE ONLY. It cannot mask a build failure: the
    /// error flag on that branch is already gated on `build.mode == .disk`,
    /// and this option is asserted `.memory`-only in `run` below. `release`,
    /// `dev` and the live server never set it.
    island_sidecar_optional: bool = false,

    pub const Mode = union(enum) {
        memory,
        disk: struct {
            check_empty_output: bool,
            output_dir_path: ?[]const u8,
        },
    };
};

pub fn run(
    io: Io,
    gpa: Allocator,
    cfg: *const Config,
    options: Options,
) error{ OutOfMemory, WriteFailed }!Build {
    assert(worker.started);

    var arena_state = std.heap.ArenaAllocator.init(gpa);
    defer arena_state.deinit();
    const arena = arena_state.allocator();

    var build: Build = blk: {
        const tracy_frame = tracy.namedFrame("load build");
        defer tracy_frame.end();
        break :blk Build.load(io, gpa, cfg, options);
    };
    _ = arena_state.reset(.retain_capacity);

    // `--summary` (issue #42). A live-server build emits no tree at all, so the
    // collector stays null there and every `if (collect)` below compiles to
    // nothing measurable for the two modes that do not print it.
    //
    // Kept as a LOCAL and threaded by pointer rather than parked on `*Build`:
    // `run` returns its `Build` BY VALUE, so a field pointing at this frame
    // would be a dangling pointer in the returned copy the moment the function
    // ends. `prerenderAll` — the one pass outside this file that emits files —
    // takes it as an explicit parameter for the same reason.
    var summary: BuildSummary = .{};
    defer summary.deinit(gpa);
    const collect: ?*BuildSummary = if (options.summary and options.mode == .disk) &summary else null;

    // Spawn the island sidecar once for the entire build, stored on *Build so
    // Build.deinit kills it. If spawn fails, fatal.msg exits loudly.
    //
    // All three args must be present, and if any is missing this leaves
    // `island_sidecar` null — which is NOT by itself an error, because a site
    // that uses no islands configures none of them. What used to make that a
    // silent failure was the render pass treating a null sidecar as
    // "pass the HTML through": a page containing `<island>` then shipped the
    // literal inert element with exit code 0. The diagnostic now lives where the
    // two facts meet — worker.zig's renderPage, which knows both that the
    // sidecar is null and that this page actually asked for an island.
    if (options.bun_path) |bun| if (options.island_sidecar) |script| if (options.island_src_dir) |root_dir| {
        build.island_sidecar = islands.Sidecar.spawn(io, bun, script, root_dir) catch |err| switch (err) {
            // The three ENOENT cases get three messages, each naming the input
            // that is actually missing (issue #82). The old single catch-all
            // stringified the raw errno beside the bun+script pair, so the
            // overwhelmingly common failure -- no `bun` on PATH -- read as
            // "render.ts is missing" about a path that resolves. `Sidecar.spawn`
            // does the disambiguation; this is where the fix goes into words.
            //
            // The bar is worker.zig's no-sidecar-configured diagnostic: name the
            // cause AND the fix. The fix here is deliberately not "install bun":
            // for an npm-installed consumer (#81) bun alone does not enable
            // islands, because the sidecar script and `@z/runtime` are supplied
            // by the Zig build integration and `@z/runtime` is unpublished.
            error.InterpreterNotFound => fatal.msg(
                "error: island sidecar interpreter not found: '{s}'\n" ++
                    "  the sidecar script '{s}' resolves — the missing thing is the interpreter itself.\n" ++
                    "  islands are server-rendered by bun at build time, wired up by build.zig's `.islands`\n" ++
                    "  (bun, the sidecar script, and the island source dir). Note that installing bun on its\n" ++
                    "  own is not enough for a toolchain-free install: the sidecar script and `@z/runtime`\n" ++
                    "  come from that Zig build integration.\n",
                .{ bun, script },
            ),
            error.SidecarScriptNotFound => fatal.msg(
                "error: island sidecar script not found: '{s}'\n" ++
                    "  this is the `render.ts` supplied by build.zig's `.islands` integration; the\n" ++
                    "  interpreter '{s}' was not the problem.\n",
                .{ script, bun },
            ),
            error.ProjectRootNotFound => fatal.msg(
                "error: island source dir not found: '{s}'\n" ++
                    "  the sidecar runs with that directory as its cwd, so bun resolves each island's\n" ++
                    "  `@z/runtime` and JSX imports from the `node_modules` beneath it. Set it to the\n" ++
                    "  site's project root in build.zig's `.islands`.\n",
                .{root_dir},
            ),
            else => fatal.msg(
                "error: failed to spawn island sidecar ({s} {s}): {s}\n",
                .{ bun, script, @errorName(err) },
            ),
        };
    };
    build.island_props_check_mode = options.island_props_check;
    // Introspection-only, and memory-only: a disk build that renders an
    // <island> with no sidecar ships an inert element, which is a build
    // error, not a preference. Assert rather than silently honour it.
    assert(!(options.island_sidecar_optional and options.mode == .disk));
    build.island_sidecar_optional = options.island_sidecar_optional;
    // The islands runtime slice, read ONCE for the whole build: the render pass
    // is multithreaded, every worker reads this and nobody writes it. This is a
    // READ, not a write — it produces no output-tree writes of its own — so it
    // sits here, above every pass, without disturbing the pass ordering
    // documented below.
    if (options.islands_slice_json) |slice_path| {
        build.islands_slice = islands_slice.load(io, gpa, slice_path) catch |err| fatal.msg(
            "error: could not read the islands runtime slice manifest '{s}': {s}\n",
            .{ slice_path, @errorName(err) },
        );
        // A build whose decision flipped SLICED -> FALLBACK leaves the previous
        // build's `/islands/_runtime.js` behind: nothing prunes the output tree
        // (`addInstallDirectory` only copies, and `--force` only skips the
        // empty-output check). Same treatment, and the same rationale, as
        // `src/spa.zig`'s `deleteStaleSlicedRuntime` (AUDF-015). It runs before
        // this build's install steps, which install nothing under that name when
        // the decision is fallback, so the deletion sticks.
        //
        // NOT gated on `!incremental`: the manifest cannot flip during an
        // incremental dev rebuild (that path only fires when every changed file
        // is a content page, and the manifest depends solely on island bundles),
        // so this is a no-op there rather than a hazard.
        //
        // Deliberately INSIDE the `islands_slice_json != null` branch, matching
        // `src/spa.zig`. An invocation that was never told about slicing — a
        // hand-written `zigapagos release`, or a ZIGAPAGOS_HOT_ISLANDS dev build,
        // where `build/bundles.zig` skips the slicer entirely — has no basis for
        // deleting a file it did not produce and knows nothing about. The cost of
        // that choice is bounded and already-familiar: an unreferenced
        // `islands/_runtime.js` can linger in an output tree that a sliced build
        // wrote earlier, exactly as the shared runtime lingers unreferenced on a
        // fully-sliced site (see docs/islands.md). Nothing points at it, so it is
        // dead weight, never a wrong runtime.
        if (build.mode == .disk) islands_slice.deleteStaleRuntime(
            io,
            build.mode.disk.output_dir,
            build.islands_slice.url == null,
        ) catch |err| fatal.msg(
            "error: could not delete the stale sliced islands runtime: {s}\n",
            .{@errorName(err)},
        );
    }
    // Dev-only: a non-null path turns on per-page island-usage
    // collection in the render workers (see worker.zig's renderPage).
    build.island_manifest_path = if (options.mode == .disk) options.island_manifest_path else null;

    var static_assets_errors = false;
    {
        const tracy_frame = tracy.namedFrame("scan content");
        defer tracy_frame.end();
        switch (build.cfg.*) {
            .Site => |s| {
                build.variants = try gpa.alloc(Variant, 1);
                worker.addJob(io, .{
                    .scan = .{
                        .variant = &build.variants[0],
                        .base_dir = build.base_dir,
                        .content_dir_path = s.content_dir_path,
                        .variant_id = 0,
                        .multilingual = null,
                        .output_path_prefix = "",
                    },
                });
            },
            .Multilingual => |ml| {
                build.variants = try gpa.alloc(Variant, ml.locales.len);
                for (ml.locales, 0..) |locale, idx| {
                    worker.addJob(io, .{
                        .scan = .{
                            .variant = &build.variants[idx],
                            .base_dir = build.base_dir,
                            .content_dir_path = locale.content_dir_path,
                            .variant_id = @intCast(idx),
                            .multilingual = .{
                                .i18n_dir = build.i18n_dir,
                                .i18n_dir_path = ml.i18n_dir_path,
                                .locale_code = locale.code,
                            },
                            .output_path_prefix = locale.output_prefix_override orelse locale.code,
                        },
                    });
                }
            },
        }

        // Before we wait for content dirs to be scanned, we scan the layouts
        // directory in this thread.
        // TODO: find a better moment for this work
        try build.scanTemplates(io, gpa, arena);
        if (builtin.mode == .Debug) {
            const Ctx = struct {
                b: *Build,
                pub fn lessThan(ctx: @This(), lid: usize, rid: usize) bool {
                    var lbuf: [std.fs.max_path_bytes]u8 = undefined;
                    var rbuf: [std.fs.max_path_bytes]u8 = undefined;

                    const keys = ctx.b.templates.entries.items(.key);
                    const lhs = std.fmt.bufPrint(&lbuf, "{f}", .{
                        keys[lid].fmt(&ctx.b.st, &ctx.b.pt, null, "/"),
                    }) catch unreachable;
                    const rhs = std.fmt.bufPrint(&rbuf, "{f}", .{
                        keys[rid].fmt(&ctx.b.st, &ctx.b.pt, null, "/"),
                    }) catch unreachable;

                    if (std.mem.order(u8, lhs, rhs) == .lt) return true;
                    return false;
                }
            };
            const ctx: Ctx = .{ .b = &build };
            build.templates.sort(ctx);
        }
        try build.scanSiteAssets(io, gpa, arena);
        _ = arena_state.reset(.retain_capacity);

        for (build.cfg.getStaticAssets()) |path| {
            // Glob form: a trailing `**` installs every asset under a prefix
            // (paths are relative to `assets_dir_path`, matching the exact-match
            // form). `**` = the whole assets tree (Astro's "copy public/"); `img/**`
            // = everything under `assets/img/`. This saves enumerating each file.
            if (std.mem.eql(u8, path, "**") or std.mem.endsWith(u8, path, "/**")) {
                // Drop the trailing `**`, keeping the directory prefix (incl. its
                // `/`): "img/**" -> "img/", "**" -> "" (matches all).
                const prefix = path[0 .. path.len - 2];
                var matched: usize = 0;
                var glob_it = build.site_assets.iterator();
                var name_buf: [std.fs.max_path_bytes]u8 = undefined;
                while (glob_it.next()) |entry| {
                    const asset_path = std.fmt.bufPrint(&name_buf, "{f}", .{
                        entry.key_ptr.fmt(&build.st, &build.pt, null, "/"),
                    }) catch continue;
                    if (prefix.len == 0 or std.mem.startsWith(u8, asset_path, prefix)) {
                        entry.value_ptr.raw = 1;
                        matched += 1;
                    }
                }
                if (matched == 0) {
                    static_assets_errors = true;
                    if (diag.format == .json) {
                        var msg_buf: [1024]u8 = undefined;
                        diag.emit(.{
                            .code = .ZP_STATIC_ASSET_GLOB_EMPTY,
                            .severity = .@"error",
                            .message = diag.render(&msg_buf, "static asset glob '{s}' matched no assets", .{path}),
                        });
                    } else {
                        std.debug.print("error: static asset glob '{s}' matched no assets\n", .{path});
                    }
                    // `build.mode == .memory` (the live server) never sees
                    // diag.format == .json: main.zig gates its `--format=`
                    // pre-scan to `zigapagos release`'s own arguments, and
                    // serve.zig's parser rejects the flag outright. So this
                    // block stays unconditional -- it is not part of the
                    // text/json split above.
                    if (build.mode == .memory) {
                        try build.mode.memory.errors.append(gpa, .{
                            .ref = "",
                            .msg = try std.fmt.allocPrint(
                                gpa,
                                "error: static asset glob '{s}' matched no assets\n",
                                .{path},
                            ),
                        });
                    }
                }
                continue;
            }

            if (PathName.get(&build.st, &build.pt, path)) |pn| {
                if (build.site_assets.getPtr(pn)) |rc| {
                    rc.raw = 1;
                    continue;
                }
            }

            static_assets_errors = true;
            if (diag.format == .json) {
                var msg_buf: [1024]u8 = undefined;
                diag.emit(.{
                    .code = .ZP_STATIC_ASSET_MISSING,
                    .severity = .@"error",
                    .message = diag.render(&msg_buf, "static asset '{s}' does not exist", .{path}),
                });
            } else {
                std.debug.print("error: static asset '{s}' does not exist\n", .{
                    path,
                });
            }

            if (build.mode == .memory) {
                try build.mode.memory.errors.append(gpa, .{
                    .ref = "",
                    .msg = try std.fmt.allocPrint(
                        gpa,
                        "error: static asset '{s}' does not exist\n",
                        .{path},
                    ),
                });
            }
        }

        worker.wait(); // variants done scanning their content + i18n ziggy file

        // Content-hashed asset filenames (issue #53). This has to sit HERE,
        // between the `static_assets` expansion above and the render pass
        // below, for two independent reasons:
        //
        //  * AFTER the expansion, because that is what marks the assets that
        //    must keep a stable name. `computeAssetFingerprints` reads the
        //    refcount to tell them apart, and at this exact point in the pass
        //    order a non-zero refcount can ONLY have come from `static_assets`
        //    — nothing has rendered yet, so no `.link()` has bumped anything.
        //  * BEFORE the render pass, because the map is consulted by the
        //    render workers (`context/Asset.zig`, `render/html.zig`) and by
        //    the SPA prerender. Filling it once here and never touching it
        //    again is what makes those lock-free reads correct.
        //
        // It also runs on the INCREMENTAL dev path, which skips the install
        // pass entirely: the pages that do re-render still have to emit the
        // same fingerprinted URLs the previous full build installed, and
        // because the name is a pure function of the file's bytes, recomputing
        // it reproduces exactly those URLs.
        if (build.mode == .disk and build.cfg.getAssetFingerprint()) {
            computeAssetFingerprints(io, gpa, &build);
        }
    }

    // Activate sections by parsing their index.smd page
    var i18n_errors = false;
    var any_content = false;
    {
        const tracy_frame = tracy.namedFrame("activate sections");
        defer tracy_frame.end();
        for (build.variants) |*v| {
            if (v.i18n_diag.errors.items.len > 0) {
                i18n_errors = true;

                var buf: [std.fs.max_path_bytes]u8 = undefined;
                const path = std.fmt.bufPrint(&buf, "{f}", .{fmtJoin('/', &.{
                    build.cfg.Multilingual.i18n_dir_path,
                    v.i18n_diag.path.?,
                })}) catch v.i18n_diag.path.?;

                v.i18n_diag.path = path;
                if (diag.format == .json) {
                    var msg_buf: [4096]u8 = undefined;
                    diag.emit(.{
                        .code = .ZP_I18N_PARSE,
                        .severity = .@"error",
                        .file = path,
                        .message = diag.render(&msg_buf, "{f}", .{v.i18n_diag.fmt(v.i18n_src)}),
                    });
                } else {
                    std.debug.print("{f}\n\n", .{v.i18n_diag.fmt(v.i18n_src)});
                }
                if (build.mode == .memory) {
                    try build.mode.memory.errors.append(gpa, .{
                        .ref = "",
                        .msg = try std.fmt.allocPrint(
                            gpa,
                            "{f}\n\n",
                            .{v.i18n_diag.fmt(v.i18n_src)},
                        ),
                    });
                }
                continue;
            }

            for (v.sections.items[1..]) |*s| {
                any_content = true;
                worker.addJob(io, .{
                    .section_activate = .{
                        .variant = v,
                        .section = s,
                        .page = &v.pages.items[s.index],
                        .drafts = options.drafts,
                        .auto_heading_ids = build.cfg.getAutoHeadingIds(),
                    },
                });
            }
        }

        // Stop if there is no content at all to analyze
        if (!any_content) fatal.msg(
            "No content found, start by adding a index.smd file to your content directory.\n",
            .{},
        );

        // Never a deadlock because we check that at least one page exists.
        worker.wait(); // sections have been activated (by parsing index.smd files)

    }
    // This second time, as we scan sections, we also propagate section
    // deactivation downward to avoid processing unreachable sections.
    var pages_to_parse: usize = 0;
    var progress_parse = progress.start("Parse pages", 0);
    var sites: std.StringArrayHashMapUnmanaged(context.Site) = .empty;
    {
        const tracy_frame = tracy.namedFrame("parse pages");
        defer tracy_frame.end();
        for (build.variants) |*v| {
            v.sections.items[0].active = true;
            for (v.sections.items[1..], 1..) |*s, idx| {
                assert(s.parent_section < idx);
                // This will access section 0 but its 'active' field is set correctly
                // (see 4 lines above)
                const parent = v.sections.items[s.parent_section];
                log.debug("section {} parent {} parent.active = {}", .{
                    idx, s.parent_section, parent.active,
                });

                if (!parent.active) s.active = false;
                if (!s.active) continue;

                pages_to_parse += s.pages.items.len;

                const index_smd: String = @enumFromInt(1);
                assert(v.string_table.get("index.smd").? == index_smd);
                for (s.pages.items) |page_index| {
                    const p = &v.pages.items[page_index];
                    if (p._scan.file.name == index_smd) continue; // already parsed
                    worker.addJob(io, .{
                        .page_parse = .{
                            .progress = progress_parse,
                            .drafts = options.drafts,
                            .variant = v,
                            .page = p,
                            .auto_heading_ids = build.cfg.getAutoHeadingIds(),
                        },
                    });
                }
            }
        }

        progress_parse.setEstimatedTotalItems(pages_to_parse);

        switch (build.cfg.*) {
            .Site => |s| {
                try sites.putNoClobber(gpa, "", .{
                    .host_url = s.host_url,
                    .title = s.title,
                    ._meta = .{
                        .variant_id = 0,
                        .kind = .{ .simple = s.url_path_prefix },
                    },
                });
            },
            .Multilingual => |ml| {
                try sites.ensureTotalCapacity(gpa, build.variants.len);
                for (ml.locales, 0..) |loc, idx| sites.putAssumeCapacityNoClobber(loc.code, .{
                    .host_url = loc.host_url_override orelse ml.host_url,
                    .title = loc.site_title,
                    ._meta = .{
                        .variant_id = @intCast(idx),
                        .kind = .{
                            .multi = loc,
                        },
                    },
                });
            },
        }

        // In case all pages are section indexes, we might have content but no
        // pages to analyze at thist stage.
        if (pages_to_parse > 0) worker.wait(); // all active pages have been loaded and parsed
        progress_parse.end();
    }

    // TODO: move this onto the worker pool, we don't need to look at
    // sections for a while after this point, ideally it would require
    // having its own waitgroup.
    for (build.variants) |*v| {
        for (v.sections.items[1..]) |*s| {
            s.sortPages(gpa, v, v.pages.items);
        }
    }

    var parse_errors = false;
    var pages_to_analyze: usize = 0;
    var progress_page_analyze = progress.start("Analyze pages", 0);
    {
        const tracy_frame = tracy.namedFrame("analyze pages");
        defer tracy_frame.end();
        for (build.variants, 0..) |*v, vidx| {
            for (v.pages.items) |*p| {
                if (!p._parse.active) continue;

                // First we need to check the frontmatter as the ast will be valid
                // only if the frontmatter has been correctly identifed as well.
                switch (p._parse.status) {
                    .empty => {
                        // Page is empty, print warning and skip it
                        if (diag.format == .json) {
                            var path_buf: [std.fs.max_path_bytes]u8 = undefined;
                            diag.emit(.{
                                .code = .ZP_EMPTY_PAGE,
                                .severity = .warning,
                                .file = diag.render(&path_buf, "{f}", .{p._scan.file.fmt(
                                    &v.string_table,
                                    &v.path_table,
                                    v.content_dir_path,
                                    "",
                                )}),
                                .message = "ignoring empty file",
                            });
                        } else {
                            std.debug.print("WARNING: Ignoring empty file '{f}'\n", .{
                                p._scan.file.fmt(
                                    &v.string_table,
                                    &v.path_table,
                                    v.content_dir_path,
                                    "",
                                ),
                            });
                        }
                        continue;
                    },

                    .frontmatter => |err| {
                        if (!parse_errors) {
                            parse_errors = true;
                        }

                        const note = switch (err) {
                            error.MissingFrontmatter => "the document doesn't start with '---' (a frontmatter frame delimiter)",
                            error.OpenFrontmatter => "the frontmatter is missing a closing '---' frontmatter delimiter",
                        };

                        if (diag.format == .json) {
                            var path_buf: [std.fs.max_path_bytes]u8 = undefined;
                            diag.emit(.{
                                .code = .ZP_FRONTMATTER_FRAMING,
                                .severity = .@"error",
                                .file = diag.render(&path_buf, "{f}", .{p._scan.file.fmt(
                                    &v.string_table,
                                    &v.path_table,
                                    v.content_dir_path,
                                    "",
                                )}),
                                .line = p._parse.fm.lines,
                                // The text-mode twin below prints a literal
                                // ':1' for the column, so JSON must say 1 too
                                // -- a null here would be the one converted
                                // site where the two modes disagree on the
                                // shape of a location.
                                .col = 1,
                                .message = "frontmatter framing error",
                                .help = note,
                            });
                        } else {
                            std.debug.print(
                                \\{f}:{}:1 error: frontmatter framing error
                                \\   {s}
                                \\
                            , .{
                                p._scan.file.fmt(
                                    &v.string_table,
                                    &v.path_table,
                                    v.content_dir_path,
                                    "",
                                ),
                                p._parse.fm.lines,
                                note,
                            });
                        }
                        if (build.mode == .memory) {
                            try build.mode.memory.errors.append(gpa, .{
                                .ref = "",
                                .msg = try std.fmt.allocPrint(gpa,
                                    \\{f}:{}:1 error: frontmatter framing error
                                    \\   {s}
                                    \\
                                , .{
                                    p._scan.file.fmt(
                                        &v.string_table,
                                        &v.path_table,
                                        v.content_dir_path,
                                        "",
                                    ),
                                    p._parse.fm.lines,
                                    note,
                                }),
                            });
                        }
                        continue;
                    },

                    // Captured as `ziggy_diag` (not `diag`, the module import
                    // above) -- this arm's local shadowed the module and every
                    // reference inside it needs to be the module now.
                    .ziggy => |*ziggy_diag| {
                        if (!parse_errors) {
                            parse_errors = true;
                        }

                        var buf: [std.fs.max_path_bytes]u8 = undefined;
                        const path = std.fmt.bufPrint(&buf, "{f}", .{
                            p._scan.file.fmt(
                                &v.string_table,
                                &v.path_table,
                                v.content_dir_path,
                                "",
                            ),
                        }) catch unreachable;

                        ziggy_diag.path = path;
                        if (diag.format == .json) {
                            var msg_buf: [4096]u8 = undefined;
                            diag.emit(.{
                                .code = .ZP_FRONTMATTER_PARSE,
                                .severity = .@"error",
                                .file = path,
                                .message = diag.render(&msg_buf, "{f}", .{ziggy_diag.fmt(p._parse.full_src)}),
                            });
                        } else {
                            std.debug.print("{f}\n\n", .{ziggy_diag.fmt(p._parse.full_src)});
                        }
                        if (build.mode == .memory) {
                            try build.mode.memory.errors.append(gpa, .{
                                .ref = "",
                                .msg = try std.fmt.allocPrint(
                                    gpa,
                                    "{f}\n\n",
                                    .{ziggy_diag.fmt(p._parse.full_src)},
                                ),
                            });
                        }
                        continue;
                    },

                    .parsed => {},
                }

                // Validate the layout field and reference count so that we
                // know to only load layouts that are actively used.
                // This is in some ways frontmatter analysis work but it's done
                // here because we have to scan all pages for errors anyway.
                layout: {
                    // Append frontmatter errors via the page's parse arena so
                    // that ownership is uniform with the worker's
                    // analyzeFrontmatter (which also appends to this list using
                    // this same arena). Appending with a bare `gpa` here would
                    // leak: Page.deinit only frees `_analysis.frontmatter`
                    // implicitly via `_parse.arena.deinit()`, which cannot
                    // reclaim allocations the arena never made.
                    var page_arena_state = p._parse.arena.promote(gpa);
                    defer p._parse.arena = page_arena_state.state;
                    const page_arena = page_arena_state.allocator();

                    const layout_pn = PathName.get(&build.st, &build.pt, p.layout) orelse {
                        // We can use analysis because a page that has
                        // parse.status == ok will have initialized the field for
                        // us.
                        try p._analysis.frontmatter.append(page_arena, .layout);
                        break :layout;
                    };

                    const layout = build.templates.getPtr(layout_pn) orelse {
                        try p._analysis.frontmatter.append(page_arena, .layout);
                        break :layout;
                    };

                    if (!layout.layout) {
                        // TODO: create a dedicated error
                        try p._analysis.frontmatter.append(page_arena, .layout);
                        break :layout;
                    }

                    for (p.alternatives, 0..) |alt, aidx| {
                        const alt_layout_pn = PathName.get(
                            &build.st,
                            &build.pt,
                            alt.layout,
                        ) orelse {
                            try p._analysis.frontmatter.append(page_arena, .{
                                .alternative = .{
                                    .id = @intCast(aidx),
                                    .kind = .layout,
                                },
                            });
                            break :layout;
                        };

                        const alt_layout = build.templates.getPtr(alt_layout_pn) orelse {
                            // We can use analysis because a page that has
                            // parse.status == ok will have initialized the field for
                            // us.
                            try p._analysis.frontmatter.append(page_arena, .{
                                .alternative = .{
                                    .id = @intCast(aidx),
                                    .kind = .layout,
                                },
                            });
                            break :layout;
                        };

                        if (!alt_layout.layout) {
                            // TODO: create a dedicated error
                            try p._analysis.frontmatter.append(page_arena, .{
                                .alternative = .{
                                    .id = @intCast(aidx),
                                    .kind = .layout,
                                },
                            });
                            break :layout;
                        }
                    }
                }

                if (p._parse.ast.errors.len > 0) {
                    if (!parse_errors) {
                        parse_errors = true;
                    }

                    printSuperMdErrors(
                        gpa,
                        arena,
                        &build,
                        v,
                        p._scan.file,
                        &p._parse.ast,
                        p._parse.full_src[p._parse.fm.offset..],
                        p._parse.fm.lines - 1,
                    );

                    // Do not schedule the page for analysis if contains parsing
                    // errors.
                    continue;
                }

                // Reaching here means that the page does not contain any parsing
                // error and can be scheduled for analysis. In theory we could
                // isolate ziggy syntax errors and only analize the supermd content
                // but it seems a minor optimization not worth the extra complexity.
                pages_to_analyze += 1;
                worker.addJob(io, .{
                    .page_analyze = .{
                        .progress = progress_page_analyze,
                        .build = &build,
                        .variant_id = @intCast(vidx),
                        .page = p,
                    },
                });
            }
        }

        progress_page_analyze.setEstimatedTotalItems(pages_to_analyze);
        worker.wait(); // pages have been analyzed
        progress_page_analyze.end();
    }

    for (build.templates.keys(), build.templates.values()) |tpn, *template| {
        worker.addJob(io, .{
            .template_parse = .{
                .build = &build,
                .template = template,
                .pn = tpn,
            },
        });
    }

    var analysis_errors = false;
    for (build.variants) |*v| {
        for (v.pages.items) |*p| {
            if (!p._parse.active) continue;
            if (p._parse.status != .parsed) continue;

            const fm_errors = &p._analysis.frontmatter;
            if (fm_errors.items.len > 0) {
                if (!analysis_errors) {
                    analysis_errors = true;
                }

                const full_src = p._parse.full_src;
                const ast = ziggy.Ast.init(
                    arena,
                    full_src,
                    false,
                    true,
                    true,
                    null,
                ) catch fatal.oom();

                for (fm_errors.items) |err| {
                    const loc = err.location(full_src, ast);
                    const sel = loc.getSelection(full_src);
                    const line_off = loc.line(full_src);

                    const line_trim_left = std.mem.trimStart(u8, line_off.line, &std.ascii.whitespace);
                    const start_trim_left = line_off.start + line_off.line.len - line_trim_left.len;

                    const caret_len = loc.end - loc.start;
                    const caret_spaces_len = loc.start -| start_trim_left;

                    const line_trim = std.mem.trimEnd(u8, line_trim_left, &std.ascii.whitespace);

                    var hl_buf: [1024]u8 = undefined;

                    const highlight = if (caret_len + caret_spaces_len < 1024) blk: {
                        const h = hl_buf[0 .. caret_len + caret_spaces_len];
                        @memset(h[0..caret_spaces_len], ' ');
                        @memset(h[caret_spaces_len..][0..caret_len], '^');
                        break :blk h;
                    } else "";

                    if (diag.format == .json) {
                        var path_buf: [std.fs.max_path_bytes]u8 = undefined;
                        diag.emit(.{
                            .code = err.code(),
                            .severity = .@"error",
                            .file = diag.render(&path_buf, "{f}", .{p._scan.file.fmt(
                                &v.string_table,
                                &v.path_table,
                                v.content_dir_path,
                                "",
                            )}),
                            .line = sel.start.line,
                            .col = sel.start.col,
                            .message = err.title(),
                        });
                    } else {
                        std.debug.print(
                            \\{f}:{}:{}: error: {s}
                            \\|    {s}
                            \\|    {s}
                            \\
                            \\
                        , .{
                            p._scan.file.fmt(
                                &v.string_table,
                                &v.path_table,
                                v.content_dir_path,
                                "",
                            ),
                            sel.start.line,
                            sel.start.col,
                            err.title(),
                            line_trim,
                            highlight,
                        });
                    }
                    if (build.mode == .memory) {
                        try build.mode.memory.errors.append(gpa, .{
                            .ref = "",
                            .msg = try std.fmt.allocPrint(gpa,
                                \\{f}:{}:{}: error: {s}
                                \\|    {s}
                                \\|    {s}
                                \\
                                \\
                            , .{
                                p._scan.file.fmt(
                                    &v.string_table,
                                    &v.path_table,
                                    v.content_dir_path,
                                    "",
                                ),
                                sel.start.line,
                                sel.start.col,
                                err.title(),
                                line_trim,
                                highlight,
                            }),
                        });
                    }
                }
            }

            const page_errors = &p._analysis.page;
            if (page_errors.items.len > 0) {
                // Error-severity check, not `.items.len > 0`: a page whose only
                // page_errors are warnings (e.g. unknown_language, see
                // PageAnalysisError.severity) must still render.
                if (!analysis_errors and context.Page.PageAnalysisError.anyError(page_errors.items)) {
                    analysis_errors = true;
                }

                for (page_errors.items) |err| {
                    const n = err.node;
                    const range = n.range();
                    const md_src = p._parse.full_src[p._parse.fm.offset..];
                    const line = blk: {
                        var it = std.mem.splitScalar(u8, md_src, '\n');
                        for (1..range.start.row) |_| _ = it.next();
                        break :blk it.next().?;
                    };

                    const line_trim_left = std.mem.trimStart(
                        u8,
                        line,
                        &std.ascii.whitespace,
                    );

                    const line_trim = std.mem.trimEnd(u8, line_trim_left, &std.ascii.whitespace);

                    const start_trim_left = line.len - line_trim_left.len;
                    const caret_len = if (range.start.row == range.end.row)
                        range.end.col - range.start.col
                    else
                        line_trim.len - start_trim_left;
                    const caret_spaces_len = range.start.col - 1 - start_trim_left;

                    var hl_buf: [1024]u8 = undefined;

                    const highlight = if (caret_len + caret_spaces_len + 1 < 1024) blk: {
                        const h = hl_buf[0 .. caret_len + caret_spaces_len + 1];
                        @memset(h[0..caret_spaces_len], ' ');
                        @memset(h[caret_spaces_len..][0 .. caret_len + 1], '^');
                        break :blk h;
                    } else "";

                    const fm_lines = p._parse.fm.lines;
                    const severity_word = @tagName(err.severity());
                    const note_line: NoteLine = .{ .note = err.note() };
                    if (diag.format == .json) {
                        var path_buf: [std.fs.max_path_bytes]u8 = undefined;
                        var msg_buf: [2048]u8 = undefined;
                        diag.emit(.{
                            .code = err.code(),
                            .severity = err.severity(),
                            .file = diag.render(&path_buf, "{f}", .{p._scan.file.fmt(
                                &v.string_table,
                                &v.path_table,
                                v.content_dir_path,
                                "",
                            )}),
                            .line = fm_lines + n.startLine(),
                            .col = n.startColumn(),
                            .message = diag.render(&msg_buf, "{f}", .{err.fmt()}),
                            .help = err.note(),
                        });
                    } else {
                        std.debug.print(
                            \\{f}:{}:{}: {s}: {f}
                            \\|    {s}
                            \\|    {s}
                            \\{f}
                            \\
                        , .{
                            p._scan.file.fmt(
                                &v.string_table,
                                &v.path_table,
                                v.content_dir_path,
                                "",
                            ),
                            fm_lines + n.startLine(),
                            n.startColumn(),
                            severity_word,
                            err.fmt(),
                            line_trim,
                            highlight,
                            note_line,
                        });
                    }

                    // Only error-severity items enter the live server's build-error
                    // list (see PageAnalysisError.severity's doc comment): that list
                    // is the "the build failed" surface, and a warning like an
                    // unknown code-fence language must not flip it.
                    if (build.mode == .memory and err.severity() == .@"error") {
                        // Contract 1 (self-freeing, NO_SLOP §2.2a): the only
                        // allocation is this one escaping `msg`, which the caller
                        // (build.mode.memory.errors) owns from here on -- same
                        // contract this call already had before NoteLine let the
                        // note collapse into the same format string instead of a
                        // second allocPrint.
                        const msg = try std.fmt.allocPrint(gpa,
                            \\{f}:{}:{}: {s}: {f}
                            \\|    {s}
                            \\|    {s}
                            \\{f}
                            \\
                        , .{
                            p._scan.file.fmt(
                                &v.string_table,
                                &v.path_table,
                                v.content_dir_path,
                                "",
                            ),
                            fm_lines + n.startLine(),
                            n.startColumn(),
                            severity_word,
                            err.fmt(),
                            line_trim,
                            highlight,
                            note_line,
                        });
                        try build.mode.memory.errors.append(gpa, .{
                            .ref = "",
                            .msg = msg,
                        });
                    }
                }
            }
        }
    }

    var translation_key_errors = false;
    if (build.cfg.* == .Multilingual) {
        for (build.variants, 0..) |*v, vidx| {
            for (v.pages.items) |*p| {
                if (!p._parse.active) continue;
                if (p._parse.status != .parsed) continue;

                // Translation keys
                if (p.translation_key) |tk| {
                    const gop = try build.tks.getOrPut(gpa, tk);
                    const locales = if (!gop.found_existing) blk: {
                        const locales = try gpa.alloc(?*context.Page, build.variants.len);
                        @memset(locales, null);
                        gop.value_ptr.* = locales;
                        break :blk locales;
                    } else gop.value_ptr.*;

                    if (locales[vidx]) |prev| {
                        // Two pages in the same locale share a translation_key —
                        // an ordinary authoring mistake. Report both pages and
                        // the key instead of aborting the build. See AUD-011.
                        translation_key_errors = true;
                        if (diag.format == .json) {
                            var path_buf: [std.fs.max_path_bytes]u8 = undefined;
                            var prev_path_buf: [std.fs.max_path_bytes]u8 = undefined;
                            var msg_buf: [2048]u8 = undefined;
                            diag.emit(.{
                                .code = .ZP_DUPLICATE_TRANSLATION_KEY,
                                .severity = .@"error",
                                // The SECOND page (the one that lost the getOrPut
                                // race) is the one carrying this diagnostic; the
                                // first page's path is folded into `message`
                                // instead of a second `file`-shaped field, since
                                // the schema has room for exactly one.
                                .file = diag.render(&path_buf, "{f}", .{p._scan.file.fmt(&v.string_table, &v.path_table, v.content_dir_path, "")}),
                                .message = diag.render(&msg_buf, "duplicate translation_key '{s}' within one locale (also defined in {s})", .{
                                    tk,
                                    diag.render(&prev_path_buf, "{f}", .{prev._scan.file.fmt(&v.string_table, &v.path_table, v.content_dir_path, "")}),
                                }),
                            });
                        } else {
                            std.debug.print(
                                \\error: duplicate translation_key '{s}' within one locale
                                \\   between  {f}
                                \\   and      {f}
                                \\
                                \\
                            , .{
                                tk,
                                prev._scan.file.fmt(&v.string_table, &v.path_table, v.content_dir_path, ""),
                                p._scan.file.fmt(&v.string_table, &v.path_table, v.content_dir_path, ""),
                            });
                        }
                        if (build.mode == .memory) {
                            try build.mode.memory.errors.append(gpa, .{
                                .ref = "",
                                .msg = try std.fmt.allocPrint(gpa,
                                    \\error: duplicate translation_key '{s}' within one locale
                                    \\   between  {f}
                                    \\   and      {f}
                                    \\
                                    \\
                                , .{
                                    tk,
                                    prev._scan.file.fmt(&v.string_table, &v.path_table, v.content_dir_path, ""),
                                    p._scan.file.fmt(&v.string_table, &v.path_table, v.content_dir_path, ""),
                                }),
                            });
                        }
                        continue;
                    }

                    locales[vidx] = p;
                }
            }
        }
    }

    // Output URL collision detection.
    // This code solves a simplified version of actual URL collision.
    // It assumes that directories can't have dots in their name, and
    // that files always have an extension, reducing collision detection
    // to just detecting duplicate paths. This simplified version
    // of the problem can be solved with a hash map, while solving the
    // full version will require using a tree for the live server
    // and perhaps some clever scan algorithm in the `zigapagos release` case.
    // Alternatively, if this algo proves to be sufficiently more efficent
    // than the tree case, we could default to this method and then only
    // switch to the more expensive approach if necessary.
    if (!parse_errors) {
        const tracy_frame = tracy.namedFrame("url collision");
        defer tracy_frame.end();
        for (build.variants) |*v| {
            for (v.pages.items, 0..) |*p, pidx| {
                if (!p._parse.active) continue;
                if (p._parse.status != .parsed) continue;

                // page_main
                // const smd_out_dir_path: []const String = smd_out: {
                //     const path = p._scan.md_path;
                //     const name = p._scan.md_name;

                //     const index_smd: String = @enumFromInt(1);
                //     const index_html: String = @enumFromInt(11);
                //     assert(v.string_table.get("index.smd").? == index_smd);
                //     assert(v.string_table.get("index.html").? == index_html);
                //     const url: PathName = blk: {
                //         if (name == index_smd) break :blk .{
                //             .path = path,
                //             .name = index_html,
                //         };

                //         const name_no_ext = std.fs.path.stem(name.slice(&v.string_table));
                //         break :blk .{
                //             .path = try v.path_table.internExtend(
                //                 gpa,
                //                 path.slice(&v.path_table),
                //                 try v.string_table.intern(gpa, name_no_ext),
                //             ),
                //             .name = index_html,
                //         };
                //     };

                //     const loc: Variant.LocationHint = .{
                //         .kind = .page_main,
                //         .id = @intCast(pidx),
                //     };

                //     const gop = try v.urls.getOrPut(gpa, url);
                //     if (!gop.found_existing) {
                //         gop.value_ptr.* = loc;
                //     } else {
                //         try v.collisions.append(gpa, .{
                //             .url = url,
                //             .loc = loc,
                //             .previous = gop.value_ptr.*,
                //         });
                //     }
                //     break :smd_out url.path.slice(&v.path_table);
                // };

                // aliases
                for (p.aliases) |a| {
                    // A malformed alias (empty, non-ASCII, backslash, no
                    // extension, or a dot in a directory component) is already
                    // reported as a frontmatter error by analyzeFrontmatter and
                    // must be skipped here: interning it would violate the
                    // structural invariants the asserts below encode (and, on an
                    // empty string, read a[0] out of bounds). See AUD-002.
                    if (!worker.validOutputPath(a)) continue;
                    assert(std.mem.indexOfScalar(u8, a, '\\') == null);
                    assert(std.fs.path.extension(a).len > 0);
                    assert(std.mem.indexOfScalar(
                        u8,
                        std.fs.path.dirnamePosix(a) orelse "",
                        '.',
                    ) == null);

                    const prefix = if (a[0] == '/')
                        &.{}
                    else blk: {
                        const prefix = p._scan.url.slice(&v.path_table);
                        try v.path_table.path_components.ensureUnusedCapacity(
                            gpa,
                            prefix.len + std.mem.count(u8, a, "/"),
                        );
                        break :blk prefix;
                    };

                    const url = try v.path_table.internPathWithName(
                        gpa,
                        &v.string_table,
                        prefix,
                        a,
                    );

                    // A content page once aliased `"404.html"` meaning to
                    // override a SPA's site-wide fallback. Resolution
                    // behaviour is inherited upstream semantics and unchanged
                    // here on purpose: the alias joined to the page's own
                    // output directory instead, landed at `404/404.html`,
                    // and the demo app kept owning the real site root — the
                    // build passed silently. This warns on that exact
                    // shape without touching resolution.
                    //
                    // Two exclusions, both anti-false-positive:
                    //  - `prefix.len == 0` (page at the site root): a
                    //    relative and a root-absolute alias resolve
                    //    identically there, so warning would be a pure
                    //    false positive.
                    //  - `index.html` is deliberately NOT in the artifact
                    //    list: a relative `old-name/index.html` is the
                    //    legitimate directory-style alias idiom, and a bare
                    //    relative `index.html` resolves onto the page's own
                    //    main output and already dies in the collision
                    //    machinery above. Warning on it buys nothing.
                    if (prefix.len > 0) {
                        const basename = std.fs.path.basenamePosix(a);
                        const is_site_wide_artifact =
                            std.mem.eql(u8, basename, "404.html") or
                            std.mem.eql(u8, basename, "robots.txt") or
                            std.mem.eql(u8, basename, "sitemap.xml");
                        if (is_site_wide_artifact) {
                            std.debug.print(
                                \\{f}: warning: alias '{s}' is relative to the page's output directory and resolves to '{f}'
                                \\    note: aliases are joined to the page's URL unless they start with '/'; write '/{s}' to target the site root
                                \\
                            , .{
                                p._scan.file.fmt(&v.string_table, &v.path_table, v.content_dir_path, ""),
                                a,
                                url.fmt(&v.string_table, &v.path_table, null, ""),
                                basename,
                            });
                        }
                    }

                    const loc: Variant.LocationHint = .{
                        .kind = .page_alias,
                        .id = @intCast(pidx),
                    };

                    const gop = try v.urls.getOrPut(gpa, url);
                    if (!gop.found_existing) {
                        gop.value_ptr.* = loc;
                    } else {
                        try v.collisions.append(gpa, .{
                            .url = url,
                            .loc = loc,
                            .previous = gop.value_ptr.*,
                        });
                    }
                }

                // alternatives
                for (p.alternatives) |alt| {
                    // See the alias note above: skip a malformed alternative
                    // output (already a frontmatter error) rather than asserting
                    // on user input. See AUD-002.
                    if (!worker.validOutputPath(alt.output)) continue;
                    assert(std.mem.indexOfScalar(u8, alt.output, '\\') == null);
                    assert(std.fs.path.extension(alt.output).len > 0);
                    assert(std.mem.indexOfScalar(
                        u8,
                        std.fs.path.dirnamePosix(alt.output) orelse "",
                        '.',
                    ) == null);

                    const prefix = if (alt.output[0] == '/')
                        &.{}
                    else blk: {
                        const prefix = p._scan.url.slice(&v.path_table);
                        try v.path_table.path_components.ensureUnusedCapacity(
                            gpa,
                            prefix.len + std.mem.count(u8, alt.output, "/") + 1,
                        );
                        break :blk p._scan.url.slice(&v.path_table);
                    };
                    const url = try v.path_table.internPathWithName(
                        gpa,
                        &v.string_table,
                        prefix,
                        alt.output,
                    );

                    const loc: Variant.LocationHint = .{
                        .kind = .{ .page_alternative = alt.name },
                        .id = @intCast(pidx),
                    };

                    const gop = try v.urls.getOrPut(gpa, url);
                    if (!gop.found_existing) {
                        gop.value_ptr.* = loc;
                    } else {
                        try v.collisions.append(gpa, .{
                            .url = url,
                            .loc = loc,
                            .previous = gop.value_ptr.*,
                        });
                    }
                }
            }
        }
    }

    // Scan-time advisory: a content directory that holds pages but no index.smd
    // never became a section (see Variant.SectionlessDir), so its pages land in
    // the enclosing section with deeper URLs, no page is built at the
    // directory's own URL, and `$page.subpages()` aimed at it returns an empty
    // list. Deliberately a WARNING and not an error -- the empty-list return is
    // documented upstream behaviour and orphan directories are a legitimate
    // URL-shaping tool (tests/rendering/simple/content/nested/ uses one on
    // purpose). Deliberately NOT appended to `build.mode.memory.errors` either:
    // that list is the live server's "the build failed" surface and makes every
    // URL answer with a build-error page, so only error-severity diagnostics may
    // enter it (the same rule PageAnalysisError.severity follows). Nothing here
    // touches `any_prerendering_error`, so a warning-only build stays exit 0.
    for (build.variants) |*v| {
        if (v.sectionless_dirs.items.len == 0) continue;

        // `dir_names` is filled in filesystem iteration order and, unlike
        // `page_names`, is never sorted -- not even in Debug builds. The
        // snapshot suite diffs stderr byte for byte, so sorting here is
        // load-bearing rather than cosmetic. Format each path once into the
        // arena and sort those bytes, instead of formatting inside a comparator.
        const Entry = struct {
            /// e.g. "content/projects/"
            dir: []const u8,
            /// e.g. "projects/" -- the URL that is NOT built.
            url: []const u8,
            /// e.g. "content/projects" -- the sibling page's path, sans ".smd".
            stem: []const u8,
            page_count: u32,
            sibling_leaf_page: bool,

            fn lessThan(_: void, a: @This(), b: @This()) bool {
                return std.mem.order(u8, a.dir, b.dir) == .lt;
            }
        };

        const entries = try arena.alloc(Entry, v.sectionless_dirs.items.len);
        for (entries, v.sectionless_dirs.items) |*e, sd| {
            e.* = .{
                .dir = try std.fmt.allocPrint(arena, "{f}", .{
                    sd.path.fmt(&v.string_table, &v.path_table, v.content_dir_path, true),
                }),
                .url = try std.fmt.allocPrint(arena, "{f}", .{
                    sd.path.fmt(&v.string_table, &v.path_table, null, true),
                }),
                .stem = try std.fmt.allocPrint(arena, "{f}", .{
                    sd.path.fmt(&v.string_table, &v.path_table, v.content_dir_path, false),
                }),
                .page_count = sd.page_count,
                .sibling_leaf_page = sd.sibling_leaf_page,
            };
        }
        std.mem.sort(Entry, entries, {}, Entry.lessThan);

        for (entries) |e| {
            std.debug.print(
                \\{s}: warning: directory has {d} {s} but no index.smd, so it is not a section
                \\|   note: its pages join the enclosing section instead, and no page is built at '{s}'
                \\
            , .{
                e.dir,
                e.page_count,
                if (e.page_count == 1) "page" else "pages",
                e.url,
            });
            if (e.sibling_leaf_page) {
                std.debug.print(
                    \\|   note: '{s}.smd' is a plain page, not this directory's index -- move it to '{s}index.smd' to make it one
                    \\
                    \\
                , .{ e.stem, e.dir });
            } else {
                std.debug.print(
                    \\|   note: create '{s}index.smd' to make it a section ($page.subpages() is empty for anything that is not one)
                    \\
                    \\
                , .{e.dir});
            }
        }
    }

    var collision_errors = false;
    for (build.variants) |v| {
        if (v.collisions.items.len > 0) {
            if (!collision_errors) {
                collision_errors = true;
            }
            for (v.collisions.items) |c| {
                if (diag.format == .json) {
                    var url_buf: [std.fs.max_path_bytes]u8 = undefined;
                    var a_buf: [std.fs.max_path_bytes]u8 = undefined;
                    var b_buf: [std.fs.max_path_bytes]u8 = undefined;
                    var msg_buf: [2048]u8 = undefined;
                    diag.emit(.{
                        .code = .ZP_URL_COLLISION,
                        .severity = .@"error",
                        // No `file`: a collision names the OUTPUT url and two
                        // source locations, none of which is a single natural
                        // fit for the schema's one `file` slot -- all three
                        // are folded into a self-contained `message` instead
                        // (this is a NEW string that exists only in JSON
                        // mode; text mode below is unchanged).
                        .message = diag.render(&msg_buf, "output url collision at '{s}' between '{s}' and '{s}'", .{
                            diag.render(&url_buf, "{f}", .{c.url.fmt(&v.string_table, &v.path_table, null, "")}),
                            diag.render(&a_buf, "{f}", .{c.previous.fmt(&v.string_table, &v.path_table, v.pages.items)}),
                            diag.render(&b_buf, "{f}", .{c.loc.fmt(&v.string_table, &v.path_table, v.pages.items)}),
                        }),
                    });
                } else {
                    std.debug.print(
                        \\{f}: error: output url collision detected
                        \\   between  {f}
                        \\   and      {f}
                        \\
                        \\
                    , .{
                        c.url.fmt(&v.string_table, &v.path_table, null, ""),
                        c.previous.fmt(&v.string_table, &v.path_table, v.pages.items),
                        c.loc.fmt(&v.string_table, &v.path_table, v.pages.items),
                    });
                }
                if (build.mode == .memory) {
                    try build.mode.memory.errors.append(gpa, .{
                        .ref = "",
                        .msg = try std.fmt.allocPrint(gpa,
                            \\{f}: error: output url collision detected
                            \\   between  {f}
                            \\   and      {f}
                            \\
                            \\
                        , .{
                            c.url.fmt(&v.string_table, &v.path_table, null, ""),
                            c.previous.fmt(&v.string_table, &v.path_table, v.pages.items),
                            c.loc.fmt(&v.string_table, &v.path_table, v.pages.items),
                        }),
                    });
                }
            }
        }
    }

    worker.wait(); // layouts are done loading

    var template_errors = false;
    for (build.templates.keys(), build.templates.values()) |tpn, *template| {
        if (template.html_ast.errors.len > 0) {
            if (!template_errors) {
                template_errors = true;
            }

            const path = try std.fmt.allocPrint(arena, "{f}", .{
                tpn.fmt(
                    &build.st,
                    &build.pt,
                    build.cfg.getLayoutsDirPath(),
                    "/",
                ),
            });

            _ = std.debug.lockStderr(&.{});
            defer std.debug.unlockStderr();

            var aw: Writer.Allocating = .init(gpa);
            defer aw.deinit();

            try template.html_ast.printErrors(
                template.src,
                path,
                &aw.writer,
            );

            if (diag.format == .json) {
                diag.emit(.{
                    .code = .ZP_TEMPLATE_PARSE,
                    .severity = .@"error",
                    .file = path,
                    .message = aw.written(),
                });
            } else {
                std.debug.print("{s}", .{aw.written()});
            }
            if (build.mode == .memory) {
                // Store an exactly-sized owned copy so Build.deinit can free it
                // (AUD-004); aw is emptied and freed by the defer.
                try build.mode.memory.errors.append(gpa, .{
                    .ref = "",
                    .msg = try aw.toOwnedSlice(),
                });
            }
            continue;
        }

        if (template.ast.errors.len > 0) {
            if (!template_errors) {
                template_errors = true;
            }

            const path = try std.fmt.allocPrint(arena, "{f}", .{
                tpn.fmt(
                    &build.st,
                    &build.pt,
                    build.cfg.getLayoutsDirPath(),
                    "/",
                ),
            });

            var aw: Writer.Allocating = .init(gpa);
            defer aw.deinit();

            template.ast.printErrors(
                template.src,
                path,
                &aw.writer,
            ) catch return error.OutOfMemory;

            if (diag.format == .json) {
                diag.emit(.{
                    .code = .ZP_TEMPLATE_PARSE,
                    .severity = .@"error",
                    .file = path,
                    .message = aw.written(),
                });
            } else {
                std.debug.print("{s}", .{aw.written()});
            }
            if (build.mode == .memory) {
                // Owned copy so Build.deinit can free it (AUD-004).
                try build.mode.memory.errors.append(gpa, .{
                    .ref = "",
                    .msg = try aw.toOwnedSlice(),
                });
            }
        }

        // Lint for the `:attr="$expr"` footgun (unknown `:` directive attribute):
        // SuperHTML evaluates the value but keeps the literal `:name`, so the real
        // attribute is never set and the asset/href silently breaks. Only a clean
        // html tree is scanned.
        if (template.html_ast.errors.len == 0) {
            var bads: std.ArrayListUnmanaged(Template.BadDirectiveAttr) = .empty;
            defer bads.deinit(gpa);
            try template.lintDirectiveAttrs(gpa, &bads);
            if (bads.items.len > 0) {
                template_errors = true;
                const path = try std.fmt.allocPrint(arena, "{f}", .{
                    tpn.fmt(&build.st, &build.pt, build.cfg.getLayoutsDirPath(), "/"),
                });

                var aw: Writer.Allocating = .init(gpa);
                defer aw.deinit();

                for (bads.items) |bad| {
                    const lc = Template.lineCol(template.src, bad.offset);
                    const bare = bad.name[1..];
                    // The aw accumulation stays UNCONDITIONAL (not gated on
                    // text mode): the memory-mode block below still needs the
                    // whole rendered text block regardless of diag.format.
                    try aw.writer.print(
                        \\{s}:{d}:{d}: error: unknown ':' directive attribute '{s}'
                        \\    SuperHTML's only ':' directives are :if, :loop, :text, :html
                        \\    (plus :props on <island>). A dynamic attribute uses the BARE name
                        \\    with a Scripty value: write {s}="$expr", not {s}="$expr"
                        \\    (the ':' form evaluates the value but keeps the ':{s}' name, so the
                        \\    real '{s}' attribute is never set).
                        \\
                        \\
                    , .{ path, lc.line, lc.col, bad.name, bare, bad.name, bare, bare });

                    if (diag.format == .json) {
                        var msg_buf: [512]u8 = undefined;
                        diag.emit(.{
                            .code = .ZP_TEMPLATE_BAD_DIRECTIVE_ATTR,
                            .severity = .@"error",
                            .file = path,
                            .line = lc.line,
                            .col = lc.col,
                            .message = diag.render(&msg_buf, "unknown ':' directive attribute '{s}'", .{bad.name}),
                            .help = "SuperHTML's only ':' directives are :if, :loop, :text, :html (plus :props on <island>); a dynamic attribute uses the bare name with a Scripty value",
                        });
                    }
                }

                // Only the accumulated TEXT block is conditional -- one line
                // per `bad` was already emitted above in JSON mode, so
                // printing the whole aw block again here would duplicate it.
                if (diag.format == .text) {
                    std.debug.print("{s}", .{aw.written()});
                }
                if (build.mode == .memory) {
                    // Owned copy so Build.deinit can free it (AUD-004).
                    try build.mode.memory.errors.append(gpa, .{
                        .ref = "",
                        .msg = try aw.toOwnedSlice(),
                    });
                }
            }
        }

        // Lint for `:` directives SuperHTML parses and then cannot honour: a
        // bare `:else` (validated at parse time, then never read, so the
        // evaluator null-unwraps its absent value and panics the renderer) and
        // `:if`/`:loop` on an element with no end tag (skip_body rewinds
        // `print_cursor` to `close.start`, which is 0 there, so the whole raw
        // template source is spliced into the page with exit code 0). Both
        // reach the renderer today; turning them into located template errors
        // here means the build aborts at the `template_errors` gate below,
        // BEFORE the output tree is touched. Only a clean html tree is scanned
        // -- on a broken one `close.start == 0` also means "unclosed element",
        // which SuperHTML already reports as `missing end tag`.
        if (template.html_ast.errors.len == 0) {
            var inert: std.ArrayListUnmanaged(Template.InertDirective) = .empty;
            defer inert.deinit(gpa);
            try template.lintInertDirectives(gpa, &inert);
            if (inert.items.len > 0) {
                template_errors = true;
                const path = try std.fmt.allocPrint(arena, "{f}", .{
                    tpn.fmt(&build.st, &build.pt, build.cfg.getLayoutsDirPath(), "/"),
                });

                var aw: Writer.Allocating = .init(gpa);
                defer aw.deinit();

                for (inert.items) |bad| {
                    const lc = Template.lineCol(template.src, bad.offset);
                    // As in the `:` directive-attribute lint above, the aw
                    // accumulation stays UNCONDITIONAL: the memory-mode block
                    // below needs the whole rendered text block whatever
                    // diag.format is. Each kind emits its own code, so a
                    // consumer switching on `code` gets the two distinct
                    // failures apart without parsing prose.
                    switch (bad.kind) {
                        .else_directive => {
                            try aw.writer.print(
                                \\{s}:{d}:{d}: error: ':else' is parsed but never evaluated
                                \\    SuperHTML validates ':else' at parse time and then has no case for
                                \\    it at render time: the evaluator reads the attribute's value, which
                                \\    a bare ':else' does not have, and panics on the null unwrap. No
                                \\    template using ':else' has ever rendered.
                                \\    Write the negated condition on a second <ctx> instead:
                                \\        <ctx :if="$cond">...</ctx>
                                \\        <ctx :if="$cond.not()">...</ctx>
                                \\
                                \\
                            , .{ path, lc.line, lc.col });

                            if (diag.format == .json) diag.emit(.{
                                .code = .ZP_TEMPLATE_ELSE_DIRECTIVE,
                                .severity = .@"error",
                                .file = path,
                                .line = lc.line,
                                .col = lc.col,
                                .message = "':else' is parsed but never evaluated",
                                .help = "SuperHTML has no render-time case for ':else'; write the negated condition on a second <ctx> ($cond, then $cond.not())",
                            });
                        },
                        .branching_without_end_tag => {
                            const is_loop = std.mem.eql(u8, bad.name, ":loop");
                            try aw.writer.print(
                                \\{s}:{d}:{d}: error: '{s}' on <{s}> can never work
                                \\    <{s}> is {s}: it has no end tag, and SuperHTML restarts a
                                \\    conditional or a loop by rewinding to the element's end tag.
                                \\    With none it rewinds to the start of the file and re-emits the
                                \\    whole template source into the page (exit code 0), or slices
                                \\    backwards and panics.
                                \\    '{s}' also only affects an element's BODY -- the tag and all of
                                \\    its attributes are emitted either way.
                                \\    {s}
                                \\        <ctx {s}="{s}"><{s} ...></ctx>
                                \\
                                \\
                            , .{
                                path,
                                lc.line,
                                lc.col,
                                bad.name,
                                bad.tag,
                                bad.tag,
                                if (bad.void_element) "a void element" else "self-closing",
                                bad.name,
                                if (is_loop)
                                    "To repeat the element, wrap it:"
                                else
                                    "To make the element itself conditional, wrap it:",
                                bad.name,
                                if (is_loop) "$items" else "$cond",
                                bad.tag,
                            });

                            if (diag.format == .json) {
                                var msg_buf: [256]u8 = undefined;
                                diag.emit(.{
                                    .code = .ZP_TEMPLATE_BRANCHING_WITHOUT_END_TAG,
                                    .severity = .@"error",
                                    .file = path,
                                    .line = lc.line,
                                    .col = lc.col,
                                    .message = diag.render(&msg_buf, "'{s}' on <{s}> can never work", .{ bad.name, bad.tag }),
                                    .help = "the element has no end tag for SuperHTML to rewind to, and the directive only affects an element's body anyway; wrap it in a <ctx> that carries the directive",
                                });
                            }
                        },
                    }
                }

                // Only the accumulated TEXT block is conditional -- one
                // diagnostic per entry was already emitted above in JSON mode,
                // so printing the whole aw block again here would duplicate it.
                if (diag.format == .text) {
                    std.debug.print("{s}", .{aw.written()});
                }
                if (build.mode == .memory) {
                    // Owned copy so Build.deinit can free it (AUD-004). These
                    // are error severity, so they DO belong in the live
                    // server's error list -- that list makes every URL answer
                    // with a build-error page, which is right for a template
                    // that cannot render and wrong for a mere warning.
                    try build.mode.memory.errors.append(gpa, .{
                        .ref = "",
                        .msg = try aw.toOwnedSlice(),
                    });
                }
            }
        }

        if (template.missing_parent) {
            if (!template_errors) {
                template_errors = true;
            }
            const path = try std.fmt.allocPrint(arena, "{f}", .{
                tpn.fmt(
                    &build.st,
                    &build.pt,
                    build.cfg.getLayoutsDirPath(),
                    "/",
                ),
            });

            const parent_name = template.ast.nodes[template.ast.extends_idx].templateValue().span.slice(template.src);
            if (diag.format == .json) {
                var msg_buf: [1024]u8 = undefined;
                diag.emit(.{
                    .code = .ZP_TEMPLATE_MISSING_PARENT,
                    .severity = .@"error",
                    .file = path,
                    .message = diag.render(&msg_buf, "extending a template that doesn't exist: template '{s}' does not exist", .{parent_name}),
                });
            } else {
                std.debug.print(
                    \\{s}: error: extending a template that doesn't exist 
                    \\   template '{s}' does not exist
                    \\
                , .{
                    path, parent_name,
                });
            }
            if (build.mode == .memory) {
                try build.mode.memory.errors.append(gpa, .{
                    .ref = "",
                    .msg = try std.fmt.allocPrint(gpa,
                        \\{s}: error: extending a template that doesn't exist 
                        \\   template '{s}' does not exist
                        \\
                    , .{
                        path, parent_name,
                    }),
                });
            }
        }
    }

    if (static_assets_errors or i18n_errors or collision_errors or
        parse_errors or analysis_errors or template_errors or
        translation_key_errors)
    {
        build.any_prerendering_error = true;
        return build;
    }

    // Incremental content re-render. When `changed_files` names a
    // set of changed content pages (a `zigapagos dev` inner-loop rebuild), we
    // render + emit ONLY those pages into the existing (persistent) output tree
    // and skip everything else. All pages are still scanned/parsed above — the
    // URL/collision/link tables must be whole for a changed page that links to
    // others to render correctly — but the expensive per-page render (SuperMD +
    // island SSR + disk write) runs only for the affected pages. Empty (a full
    // release build, or the dev loop's full-rebuild fallback) renders every page.
    const incremental = build.mode == .disk and options.changed_files.len > 0;
    var changed_set: std.StringHashMapUnmanaged(void) = .empty;
    defer if (builtin.mode == .Debug) changed_set.deinit(gpa);
    if (incremental) {
        try changed_set.ensureUnusedCapacity(gpa, @intCast(options.changed_files.len));
        for (options.changed_files) |cf| changed_set.putAssumeCapacity(cf, {});
    }

    // Release-time SPA prerender pass: route skeletons, dynamic-route shells,
    // per-namespace routing manifests, and the site-wide 404.html. No-ops when no
    // SPAs are declared.
    //
    // Runs BEFORE the page-render pass, and the ordering is the point. This pass
    // is the one that executes the author's own code (the sidecar runs
    // `.spa.tsx`'s `describe`/`staticPaths` to enumerate routes) and it is where
    // the spec-level invariants are checked — overlapping bases, basename
    // collisions, an unknown `--spa-not-found`, `..` in a route path, colliding
    // `_shell.html` output paths, a declared SPA with no sidecar. Every one of
    // those aborts BEFORE this pass writes its first file. Running it after the
    // page pass meant the common SPA failure fataled with the whole output tree
    // already rewritten: new page HTML beside the previous build's SPA shells,
    // routing manifests and build assets, with nothing on disk marking the tree as
    // half-updated — and `zigapagos dev` then reporting "still serving the
    // previous build", which was false. Measured on the fixture in
    // `tests/spa/prerender-order.sh`, a failed build rewrote all 16 pages before
    // aborting; it now rewrites none.
    //
    // It does NOT make the tree atomic, and this comment should not be read as
    // claiming that: a failure *partway through writing* shells still leaves
    // partial output, and a page-render failure still fails after pages are
    // emitted. What it buys is that the large majority of SPA failure modes —
    // every validation error, a missing sidecar, and any throw during route
    // enumeration — now abort with the output tree exactly as the previous build
    // left it.
    //
    // Guarded on `.disk and !incremental` because this used to sit below the
    // `mode == .memory` and `incremental` early returns: the live server never
    // prerenders, and an incremental rebuild re-emits only changed pages while
    // the previous full build's shells stay valid.
    //
    // One deliberate precedence change: the site-wide `404.html` this pass writes
    // is now written before the page pass, so a content page explicitly aliased to
    // `404.html` overwrites the SPA fallback rather than losing to it. That reads
    // as the better precedence — an explicit alias is more specific intent than a
    // fallback — and site assets named `404.html` already outranked the SPA one,
    // since asset install has always run last.
    //
    // `prerenderAll`'s inferred error set is wider than `run`'s explicit
    // `{OutOfMemory, WriteFailed}` (sidecar RPC failures, disk IO errors, ...),
    // so — matching this file's convention for OS/sidecar calls elsewhere
    // (see the sidecar-spawn call above, and worker.zig's write call sites) —
    // failures are converted to a loud fatal exit rather than propagated.
    if (build.mode == .disk and !incremental) {
        @import("spa.zig").prerenderAll(io, gpa, &build, cfg, collect) catch |err| switch (err) {
            error.OutOfMemory => fatal.oom(),
            else => fatal.msg("error: SPA prerender failed: {s}\n", .{@errorName(err)}),
        };
    }

    var pages_to_render: usize = 0;
    var progress_page_render = progress.start("Render pages", 0);
    {
        const tracy_frame = tracy.namedFrame("page rendering");
        defer tracy_frame.end();
        var path_buf: [std.fs.max_path_bytes]u8 = undefined;
        for (build.variants) |*v| {
            for (v.pages.items) |*p| {
                if (!p._parse.active) continue;
                if (p._parse.status != .parsed) continue;
                if (p._analysis.frontmatter.items.len > 0) continue;
                // Error-severity check, not `.items.len > 0`: a warning-only page
                // (e.g. an unknown code-fence language, see PageAnalysisError.severity)
                // must still render, or the flag/warning design silently drops the page.
                if (context.Page.PageAnalysisError.anyError(p._analysis.page.items)) continue;

                // Incremental: skip any page whose source file did not change.
                // Its output from the previous full build is still on disk.
                if (incremental) {
                    // `catch continue` here meant "a path too long to format is an
                    // unchanged page": the edit was accepted, the log claimed an
                    // incremental rebuild, and the previous build's HTML stayed on
                    // disk. Overflow is reachable — `path_buf` is max_path_bytes,
                    // but the formatted value is content_dir_path ++ "/" ++ a
                    // walk-relative path that is itself only bounded by
                    // max_path_bytes. Fail loudly instead; worker.zig:1239 formats
                    // this same string for the manifest, so the two must agree or a
                    // manifest key and a changed-set key silently diverge.
                    const src_path = std.fmt.bufPrint(&path_buf, "{f}", .{
                        p._scan.file.fmt(&v.string_table, &v.path_table, v.content_dir_path, "/"),
                    }) catch |err| fatal.msg(
                        "error: content path too long to format for the incremental change set ({s}): {f}\n",
                        .{
                            @errorName(err),
                            p._scan.file.fmt(&v.string_table, &v.path_table, v.content_dir_path, "/"),
                        },
                    );
                    if (!changed_set.contains(src_path)) continue;
                }

                pages_to_render += 1;

                if (builtin.single_threaded) std.debug.print("Rendering {f}...\n", .{
                    p._scan.file.fmt(&v.string_table, &v.path_table, v.content_dir_path, "/"),
                });

                const alts = try gpa.alloc(
                    @typeInfo(@TypeOf(p._render.alternatives)).pointer.child,
                    p.alternatives.len,
                );
                // Initialize to the empty state so `Page.deinit` can free every
                // element unconditionally even in .disk mode (where the worker
                // writes straight to disk and never populates these). AUD-004.
                for (alts) |*a| a.* = .{ .out = "", .errors = "" };
                p._render = .{
                    .out = "",
                    .errors = "",
                    .alternatives = alts,
                };

                worker.addJob(io, .{
                    .page_render = .{
                        .progress = progress_page_render,
                        .build = &build,
                        .sites = &sites,
                        .page = p,
                        .kind = .main,
                    },
                });

                for (0..p.alternatives.len) |aidx| {
                    worker.addJob(io, .{
                        .page_render = .{
                            .progress = progress_page_render,
                            .build = &build,
                            .sites = &sites,
                            .page = p,
                            .kind = .{ .alternative = @intCast(aidx) },
                        },
                    });
                }

                // `--summary` bookkeeping, recorded HERE — beside the jobs that
                // do the writing, and past every `continue` that skips a page —
                // so the inventory lists exactly the set this build emits
                // rather than a second, independently-derived guess at it. The
                // three path helpers are the ones `renderPage` itself formats
                // its output paths with (and that `zigapagos explain` reports),
                // so a divergence between the report and the tree would have to
                // be a divergence inside a single shared function.
                if (collect) |sm| {
                    const main_path = try worker.mainOutputPath(gpa, build.cfg, v, p);
                    defer gpa.free(main_path);
                    try sm.add(gpa, .page, main_path);
                    // `validOutputPath` mirrors `explain`: a page that reached
                    // this loop has already passed analysis, which rejects an
                    // invalid alias/alternative as a page error, so this filter
                    // is belt-and-braces rather than load-bearing.
                    for (p.aliases) |a| {
                        if (!worker.validOutputPath(a)) continue;
                        const alias_path = try worker.suffixedOutputPath(gpa, build.cfg, v, p, a);
                        defer gpa.free(alias_path);
                        try sm.add(gpa, .page_alias, alias_path);
                    }
                    for (p.alternatives) |alt| {
                        if (!worker.validOutputPath(alt.output)) continue;
                        const alt_path = try worker.suffixedOutputPath(gpa, build.cfg, v, p, alt.output);
                        defer gpa.free(alt_path);
                        try sm.add(gpa, .page_alternative, alt_path);
                    }
                }
            }
        }

        progress_page_render.setEstimatedTotalItems(pages_to_render);
        worker.wait(); // pages done rendering
        progress_page_render.end();
    }

    // Build-time typed props contract: all pages rendered, so the collector
    // holds every resolved (src, props) pair. Run the single tsc gate now.
    if (build.island_props_check_mode != .off and build.island_props_checks.items.len > 0) {
        if (options.bun_path) |bun| if (options.island_src_dir) |root_dir| {
            const props_check = @import("islands/props_check.zig");
            const res = props_check.run(io, gpa, build.island_props_checks.items, .{
                .mode = build.island_props_check_mode,
                .bun_path = bun,
                .website_root = root_dir,
            }) catch |err| blk: {
                log.err("island props check failed to run: {s}", .{@errorName(err)});
                break :blk props_check.RunResult{ .checked = 0, .skipped_no_props = 0, .mismatches = 1 };
            };
            if (res.mismatches > 0 and build.island_props_check_mode == .err) {
                build.any_rendering_error.store(true, .release);
            }
        };
    }

    if (build.mode == .memory) return build;

    // Dev-only island-usage manifest, written after the render
    // phase so it reflects exactly the mounts this build derived.
    if (options.island_manifest_path) |mpath|
        writeIslandManifest(io, gpa, &build, mpath, incremental, &changed_set);

    // An incremental rebuild re-emits ONLY the changed pages
    // (done above). The SPA prerender + site-asset install passes below
    // regenerate the WHOLE tree, so skip them: an incremental rebuild is only
    // entered when every changed file is a content page or a manifest-resolved
    // island source (`zigapagos dev` classifies the change set), and the
    // previous full build already staged everything else. Build assets are the
    // exception: an island-source edit rebundles islands/<name>.js
    // (an install_always asset) in the surrounding `zig build`, so they must
    // still be (re)installed — `updateFile` is a cheap stat-compare no-op for
    // unchanged files. Anything the dev loop can't prove is localizable falls
    // back to a full rebuild (empty `changed_files`), which runs every pass
    // as before.
    if (incremental) {
        try installBuildAssets(io, gpa, &build, collect);
        return build;
    }

    // The SPA prerender pass ran BEFORE the page-render pass above (see the long
    // comment at its call site for why). It still precedes this asset-install
    // phase, which is the ordering constraint it actually has: the
    // `spa/<name>.js` bundle is an `install_always` asset whose refcount
    // `prerenderAll` bumps, and it must land alongside the prerendered shells.
    var progress_install_assets = progress.start("Install assets", 0);
    for (build.variants) |*v| {
        worker.addJob(io, .{
            .variant_assets_install = .{
                .progress = progress_install_assets,
                .install_dir = build.mode.disk.output_dir,
                .variant = v,
            },
        });
    }

    // install site assets
    {
        const site_assets_install_dir = switch (build.cfg.*) {
            .Site => build.mode.disk.output_dir,
            .Multilingual => |ml| blk: {
                if (ml.assets_prefix_path.len == 0) {
                    break :blk build.mode.disk.output_dir;
                } else {
                    // The prefix subdir does not exist on a fresh output tree —
                    // nothing else in the release path creates it — so create it
                    // (matching how Build.load provisions every other dir) rather
                    // than `openDir`'ing it, which would `FileNotFound`-abort the
                    // whole release.
                    break :blk build.mode.disk.output_dir.createDirPathOpen(
                        io,
                        ml.assets_prefix_path,
                        .{},
                    ) catch |err| fatal.dir(ml.assets_prefix_path, err);
                }
            },
        };

        var buf: [std.fs.max_path_bytes]u8 = undefined;
        // Wider than `buf` by exactly what a fingerprint adds — `.` plus
        // `hash_len` hex digits — so that a source path which fits in `buf`
        // has a destination that provably fits here, and the `catch
        // unreachable` below stays as sound as the one above it.
        var dest_buf: [std.fs.max_path_bytes + 1 + fingerprint.hash_len]u8 = undefined;
        var site_it = build.site_assets.iterator();
        while (site_it.next()) |entry| {
            const key = entry.key_ptr.*;
            // const path = buf[0..key.path.bytesSlice(
            //     &build.st,
            //     &build.pt,
            //     &buf,
            //     std.fs.path.sep,
            //     key.name,
            // )];

            const path = std.fmt.bufPrint(&buf, "{f}", .{
                key.fmt(
                    &build.st,
                    &build.pt,
                    null,
                    "",
                ),
            }) catch unreachable;

            if (entry.value_ptr.raw > 0) {
                // The SOURCE path is `path`; the DESTINATION is the same
                // thing with the fingerprinted basename substituted (issue
                // #53). `fingerprint.fmtUrl` is the single place that decides
                // that name — the same formatter the three URL-printing seams
                // use — so an installed file and every link to it cannot
                // disagree. With fingerprinting off (or for a `static_assets`
                // entry) the map has no entry and this reproduces `path`
                // byte-for-byte.
                const dest = std.mem.trimStart(u8, std.fmt.bufPrint(&dest_buf, "{f}", .{
                    fingerprint.fmtUrl(
                        key,
                        &build.st,
                        &build.pt,
                        &build.asset_fingerprints,
                    ),
                }) catch unreachable, "/");
                // Minify text assets (currently `.css`) through Bun
                // during release staging, matching the island/SPA JS minify
                // pass. Gated on `css_minify_driver` being threaded — only the
                // disk-mode (release) build sets it, so the in-memory live
                // server (dev loop) always takes the verbatim copy below.
                if (collect) |sm| try sm.add(gpa, .site_asset, dest);
                if (shouldMinifyCss(path, options)) {
                    installMinifiedCss(
                        io,
                        gpa,
                        build.site_assets_dir,
                        site_assets_install_dir,
                        path,
                        dest,
                        options.bun_path.?,
                        options.css_minify_driver.?,
                    );
                } else {
                    _ = build.site_assets_dir.updateFile(
                        io,
                        path,
                        site_assets_install_dir,
                        dest,
                        .{},
                    ) catch |err| fatal.file(path, err);
                }
            }
        }
    }

    try installBuildAssets(io, gpa, &build, collect);

    worker.wait(); // done installing assets
    progress_install_assets.end();

    // Page assets are the ONE category not recorded at its write: they are
    // installed by `Variant.installAssets` on the worker threads whose jobs
    // were queued above. This re-states that function's filter (a `urls` entry
    // of kind `.page_asset` with a non-zero refcount) and its install-path
    // expression, so the two must be kept in step by hand — which is why
    // `tests/summary/summary.sh` compares the whole printed set against the
    // emitted tree rather than only spot-checking a path.
    if (collect) |sm| {
        for (build.variants) |*v| {
            var url_it = v.urls.iterator();
            while (url_it.next()) |entry| {
                if (entry.value_ptr.kind != .page_asset) continue;
                if (entry.value_ptr.kind.page_asset.raw == 0) continue;
                var asset_buf: [std.fs.max_path_bytes]u8 = undefined;
                const install_path = std.fmt.bufPrint(&asset_buf, "{s}{s}{f}", .{
                    v.output_path_prefix,
                    if (v.output_path_prefix.len > 0) "/" else "",
                    entry.key_ptr.fmt(&v.string_table, &v.path_table, null, ""),
                }) catch continue;
                try sm.add(gpa, .page_asset, install_path);
            }
        }
    }

    // Issue #54: every site asset whose refcount is still zero was just
    // silently dropped from the output. Say so. This runs only on the FULL
    // disk path — the `incremental` early return above is what keeps it
    // honest, since an incremental rebuild only re-derives the refcounts of
    // the pages that changed and would report every asset the rest of the
    // site links as pruned.
    reportPrunedSiteAssets(gpa, &build);

    // `--summary` (issue #42), printed LAST: the asset-install phase above must
    // stay last among the passes, so this is the first moment the inventory is
    // complete.
    //
    // On STDOUT, unlike the pruned-asset warning three lines up. That warning
    // is a diagnostic the user did not ask for and belongs with the rest of the
    // build's chatter; this is a report the user asked for by name, and the
    // whole point of issue #42 is that somebody wanted to read (and grep, and
    // diff) what a build emitted — which means it has to be separable from the
    // build log. `--format=json`'s NDJSON diagnostics go to stderr, so stdout
    // is free.
    //
    // A build with rendering errors gets a one-line refusal instead of an
    // inventory. Its output tree is genuinely incomplete — `worker.zig` marks a
    // failed page and carries on, and `cli/release.zig` turns the flag into a
    // non-zero exit *after* this returns — so a list printed here would name
    // files that were never written. Same fail-closed reasoning as
    // `reportPrunedSiteAssets` and `writeIslandManifest`.
    if (collect) |sm| {
        if (build.any_rendering_error.load(.acquire)) {
            std.debug.print(
                "summary: not printed — this build had rendering errors, so its output tree is incomplete\n",
                .{},
            );
        } else {
            var out_buf: [8 * 1024]u8 = undefined;
            // `writerStreaming`, not `writer`: the positional writer tracks its
            // own file offset, which corrupts the output of `cmd >f 2>&1` where
            // stderr has already advanced the shared one (issue #78).
            var fw = std.Io.File.stdout().writerStreaming(io, &out_buf);
            sm.render(
                &fw.interface,
                options.mode.disk.output_dir_path orelse "public",
            ) catch |err| fatal.msg("error writing the build summary to stdout: {t}\n", .{err});
            fw.interface.flush() catch |err| fatal.msg(
                "error writing the build summary to stdout: {t}\n",
                .{err},
            );
        }
    }

    return build;
}

/// Fill `build.asset_fingerprints` (issue #53). One entry per site asset that
/// is eligible for a content-hashed filename; assets left OUT of the map keep
/// their verbatim name everywhere.
///
/// Two exclusions, both deliberate:
///
///  * `rc > 0` — a `static_assets` entry. See the call site for why a non-zero
///    refcount at this point in the pass order means exactly that, and
///    `fingerprint.zig`'s header for why those must keep a stable path.
///  * A file that cannot be read. That is not fatal here: an unreadable asset
///    that nothing links is not an error at all today (it is simply never
///    installed), and one that IS linked already fails with a proper
///    `fatal.file` in the install pass, which reports the same errno with the
///    path the user actually wrote. Failing here instead would turn a
///    never-installed broken symlink in `assets/` into a hard build failure
///    the moment fingerprinting is switched on.
///
/// Cost: this reads every non-static asset once, including ones nothing ends
/// up linking, because which assets are referenced is not known until the
/// render pass has run and the URLs are needed *during* it. That is the price
/// of the feature and the reason it is opt-in.
///
/// Allocator contract: self-freeing (NO_SLOP §2.2a contract 1) for its own
/// scratch — every file buffer it reads is freed before returning. The names
/// it stores into `build.asset_fingerprints` are gpa-owned by `Build` and
/// freed in `Build.deinit`.
fn computeAssetFingerprints(io: Io, gpa: Allocator, build: *Build) void {
    const zone = tracy.trace(@src());
    defer zone.end();

    var p = progress.start("Fingerprint assets", build.site_assets.count());
    defer p.end();

    var buf: [std.fs.max_path_bytes]u8 = undefined;
    var it = build.site_assets.iterator();
    while (it.next()) |entry| {
        p.completeOne();
        if (entry.value_ptr.raw > 0) continue; // `static_assets`: stable path

        const path = std.fmt.bufPrint(&buf, "{f}", .{
            entry.key_ptr.fmt(&build.st, &build.pt, null, "/"),
        }) catch continue;

        // Streamed, not slurped: this pass reads EVERY non-`static_assets`
        // file, so a single large asset (a video, a PDF) would otherwise set
        // the build's peak RSS just to be named. See `fingerprint.hashFile`.
        const name = fingerprint.hashFile(
            gpa,
            io,
            build.site_assets_dir,
            path,
            entry.key_ptr.name.slice(&build.st),
        ) catch |err| switch (err) {
            error.OutOfMemory => fatal.oom(),
            else => continue,
        };
        build.asset_fingerprints.putNoClobber(
            gpa,
            entry.key_ptr.*,
            name,
        ) catch fatal.oom();
    }
}

/// Does `assets_dir_path` name a directory that is ALSO a content dir?
///
/// Nothing forbids it, and several of this repo's own fixtures do it
/// (`.assets_dir_path = "content"`). In that configuration `scanSiteAssets`
/// picks up every `.smd` page source as a site asset, none of which anything
/// ever `.link()`s — so the pruned-asset report (issue #54) would name the
/// site's entire content tree and be worthless. It is switched off there
/// rather than filtered by extension, because the problem is not `.smd`
/// specifically: once the two directories coincide, "an asset nothing
/// references" stops distinguishing an orphaned image from an ordinary page.
///
/// The real projects in this tree (`site/`, `examples/tsx-site/`, and the
/// `zigapagos init` template) all give assets their own directory, which is
/// also the fix for a site that wants the report back.
///
/// NO_SLOP.md §2.2a contract 3 (caller-buffer): allocates nothing.
fn assetsDirIsContentDir(cfg: *const Config) bool {
    const assets = normalizeDirPath(cfg.getAssetsDirPath());
    switch (cfg.*) {
        .Site => |s| return std.mem.eql(u8, assets, normalizeDirPath(s.content_dir_path)),
        .Multilingual => |m| {
            // Any locale is enough: one overlapping content dir already fills
            // the report with that locale's pages.
            for (m.locales) |l| {
                if (std.mem.eql(u8, assets, normalizeDirPath(l.content_dir_path))) return true;
            }
            return false;
        },
    }
}

/// Strip the spellings of a config dir path that denote the same directory, so
/// `assetsDirIsContentDir` compares directories rather than strings.
///
/// `"./content"`, `"content/"` and `"content"` are one directory as far as
/// every other consumer of these fields is concerned (they are all handed to
/// `Io.Dir.openDir`), and an exact `mem.eql` between two of those spellings
/// answered "different" — which quietly turned the pruned-asset report back ON
/// for the very configuration it is meant to suppress, naming the site's whole
/// content tree. Deliberately conservative: leading `./` and trailing `/` only,
/// no `..` resolution and no symlink following, because this decides whether to
/// print a warning and must never touch the filesystem.
///
/// NO_SLOP.md §2.2a contract 3 (caller-buffer): allocates nothing; the result
/// is a slice of the input.
fn normalizeDirPath(path: []const u8) []const u8 {
    var p = path;
    while (std.mem.startsWith(u8, p, "./")) p = p[2..];
    while (p.len > 1 and p[p.len - 1] == '/') p = p[0 .. p.len - 1];
    return p;
}

/// Is `name` a version-control placeholder for an otherwise-empty directory
/// rather than a real asset?
///
/// `.keep`/`.gitkeep` exist because git cannot track an empty directory, so
/// any project that ships a scaffolded-but-still-empty `assets/` has one. They
/// are never meant to be referenced and never meant to be installed, so
/// reporting them as "pruned" (issue #54) is pure noise — and a warning that
/// fires on every fresh site is a warning people stop reading, which is the
/// failure mode this report exists to avoid. Four of this repo's own snapshot
/// fixtures tripped it before this exclusion existed.
///
/// Deliberately an exact-name match on the two conventional spellings, not a
/// blanket "skip dotfiles": `assets/.well-known/…` and `assets/.htaccess` are
/// real deployable files, and `Build.scanSiteAssets` already documents that
/// hidden files in `assets/` are scanned on purpose.
///
/// NO_SLOP.md §2.2a contract 3 (caller-buffer): allocates nothing.
fn isDirectoryPlaceholder(name: []const u8) bool {
    return std.mem.eql(u8, name, ".keep") or std.mem.eql(u8, name, ".gitkeep");
}

