/// Renders as `|   note: <text>\n` when `note` is non-null, or nothing at all
/// otherwise. Lets a single diagnostic format string carry an optional note
/// line via `{f}` instead of branching into two near-identical format
/// strings (one with the note line spliced in, one without) -- used by both
/// the page-analysis print loop in `run` and, indirectly, the pattern
/// `printSuperMdErrors` follows for its own (fixed-literal) note below.
/// Allocation-free: it writes straight to the destination writer rather than
/// building an intermediate string, so it's sound even on the disk-mode path
/// where nothing else here allocates.
const NoteLine = struct {
    note: ?[]const u8,

    pub fn format(self: NoteLine, w: *Writer) !void {
        if (self.note) |n| try w.print("|   note: {s}\n", .{n});
    }
};

fn printSuperMdErrors(
    gpa: Allocator,
    arena: Allocator,
    build: *Build,
    v: *Variant,
    file: PathName,
    ast: *const supermd.Ast,
    md_src: []const u8,
    fm_lines: usize,
) void {
    _ = arena;
    errdefer |err| switch (err) {
        error.OutOfMemory => fatal.oom(),
    };

    // \\It's strongly recommended to setup your editor to
    // \\leverage the `supermd` CLI tool in order to obtain
    // \\in-editor syntax checking and autoformatting.
    // \\
    // \\Download it from here:
    // \\   https://github.com/kristoff-it/supermd

    for (ast.errors) |err| {
        const range = err.main;
        const line = blk: {
            var it = std.mem.splitScalar(u8, md_src, '\n');
            for (1..range.start.row) |_| _ = it.next();
            break :blk it.next().?;
        };

        const line_trim_left = std.mem.trimStart(
            u8,
            line,
            &std.ascii.whitespace,
        );

        const line_trim = std.mem.trimEnd(u8, line_trim_left, &std.ascii.whitespace);

        const start_trim_left = line.len - line_trim_left.len;
        const caret_len = if (range.start.row == range.end.row)
            range.end.col - range.start.col
        else
            line_trim.len - start_trim_left;
        const caret_spaces_len = range.start.col - 1 - start_trim_left;

        var buf: [1024]u8 = undefined;

        const extra: u32 = if (err.kind == .scripty) 1 else 0;

        const highlight = if (caret_len + caret_spaces_len + extra < 1024) blk: {
            const h = buf[0 .. caret_len + caret_spaces_len + extra];
            @memset(h[0..caret_spaces_len], ' ');
            @memset(h[caret_spaces_len..][0 .. caret_len + extra], '^');
            break :blk h;
        } else "";

        const msg = switch (err.kind) {
            .scripty => |s| s.err,
            else => "",
        };

        // std.debug.print("fm: {}\nerr: {s}\nrange start: {any}\nrange end: {any}", .{
        //     fm_offset,
        //     @tagName(err.kind),
        //     err.main.start,
        //     err.main.end,
        // });

        // Saturating subtraction because of a bug related to html comments
        // in markdown.
        // const lines = range.end.row -| range.start.row;
        // const lines_fmt = if (lines == 0) "" else try std.fmt.allocPrint(
        //     arena,
        //     "(+{} lines)",
        //     .{lines},
        // );

        const tag_name = switch (err.kind) {
            .html => |h| switch (h.tag) {
                inline else => |_, t| @tagName(t),
            },
            else => @tagName(err.kind),
        };
        // issue #32: SuperMD's `pathValidationError` rejects an empty path with
        // the bare message "path is empty". That fires on `$link.page('')`, which
        // looks like it should work because `$site.page('')` does (base.shtml's
        // nav uses it for the home link) -- but the right builtin for "link to
        // the site's home page" is `$link.site()`, which supermd's own `page`
        // builtin DESCRIPTION already names, just never in the error itself.
        // supermd is an external dependency pinned in build.zig.zon (fork policy:
        // upstream syncs at release tags only), so this hint can't be added at
        // the source -- this printing path is the legitimate in-repo enrichment
        // point instead. Matching the exact upstream string is deliberate and
        // degrades gracefully: if a release-tag sync rewords "path is empty" the
        // hint just stops firing, and tests/rendering/empty-page-path-hint.sh
        // (which asserts on it) goes red at sync time rather than silently
        // drifting. The `.page(` substring check on the source line is what
        // keeps this off `$image.asset('')` and friends, where "link to the site
        // homepage" would be actively wrong -- `sub('')`/`sibling('')` are
        // deliberately NOT hinted for the same reason (see issue #32 scope cut).
        const empty_page_path_hint = err.kind == .scripty and
            std.mem.eql(u8, msg, "path is empty") and
            std.mem.indexOf(u8, line_trim, ".page(") != null;

        // The JSON `help` value mirrors whichever note text mode would have
        // printed as the second `std.debug.print` block below -- computed
        // once here so both branches (and the `.memory` block further down)
        // read from a single source instead of re-deriving it.
        var help_buf: [256]u8 = undefined;
        const help_text: ?[]const u8 = switch (err.kind) {
            .duplicate_id => |dup| diag.render(&help_buf, "original was defined on line {}", .{fm_lines + dup.original.range().start.row}),
            else => if (empty_page_path_hint)
                "to link to the site homepage, use $link.site()"
            else
                null,
        };

        if (diag.format == .json) {
            var path_buf: [std.fs.max_path_bytes]u8 = undefined;
            var msg_buf: [1024]u8 = undefined;
            diag.emit(.{
                .code = .ZP_SUPERMD,
                .severity = .@"error",
                .file = diag.render(&path_buf, "{f}", .{file.fmt(&v.string_table, &v.path_table, v.content_dir_path, "")}),
                .line = fm_lines + range.start.row,
                .col = range.start.col,
                .message = diag.render(&msg_buf, "[{s}] {s}", .{ tag_name, msg }),
                .help = help_text,
            });
        } else {
            std.debug.print(
                \\{f}:{}:{}: [{s}] {s}
                \\|    {s}
                \\|    {s}
                \\
            , .{
                file.fmt(&v.string_table, &v.path_table, v.content_dir_path, ""),
                fm_lines + range.start.row,
                range.start.col,
                tag_name,
                msg,
                line_trim,
                highlight,
            });

            switch (err.kind) {
                .duplicate_id => |dup| {
                    std.debug.print(
                        \\|   note: original was defined on line {}
                        \\
                        \\
                    , .{fm_lines + dup.original.range().start.row});
                },
                else => if (empty_page_path_hint) {
                    std.debug.print(
                        \\|   note: to link to the site homepage, use $link.site()
                        \\
                        \\
                    , .{});
                } else {
                    std.debug.print("\n", .{});
                },
            }
        }

        if (build.mode == .memory) {
            // Unlike the `.duplicate_id` note above (a pre-existing gap this
            // change isn't retrofitting), the empty-page-path hint is added to
            // BOTH output paths, so the live server's error overlay carries it too.
            //
            // `note_segment` is one of two comptime string literals -- the hint
            // text is fixed (unlike NoteLine's dynamic PageAnalysisError notes
            // above), so a plain conditional is enough to collapse this to ONE
            // allocPrint instead of branching into two near-identical ones. It
            // carries its own trailing "\n" so the format string's final blank
            // line reproduces the same "note line + blank separator" shape either
            // way (see the analogous NoteLine reasoning above).
            const note_segment: []const u8 = if (empty_page_path_hint)
                "|   note: to link to the site homepage, use $link.site()\n"
            else
                "";
            // Contract 1 (self-freeing, NO_SLOP §2.2a): `memory_msg` is the only
            // allocation and it escapes as-is into build.mode.memory.errors, which
            // owns it from here on.
            const memory_msg = try std.fmt.allocPrint(gpa,
                \\{f}:{}:{}: [{s}] {s}
                \\|    {s}
                \\|    {s}
                \\{s}
                \\
            , .{
                file.fmt(&v.string_table, &v.path_table, v.content_dir_path, ""),
                fm_lines + range.start.row,
                range.start.col,
                tag_name,
                msg,
                line_trim,
                highlight,
                note_segment,
            });
            try build.mode.memory.errors.append(gpa, .{
                .ref = "",
                .msg = memory_msg,
            });
        }
    }
}

pub fn fmtJoin(sep: u8, paths: []const []const u8) FormatJoin {
    return .{ .paths = paths, .sep = sep };
}

pub const FormatJoin = struct {
    paths: []const []const u8,
    sep: u8,

    pub fn format(fj: FormatJoin, w: *Writer) !void {
        assert(fj.sep == '/' or fj.sep == '\\');

        const paths = fj.paths;
        const separator = fj.sep;

        const first_path_idx = for (paths, 0..) |p, idx| {
            if (p.len != 0) break idx;
        } else return;

        try w.writeAll(paths[first_path_idx]); // first component
        var prev_path = paths[first_path_idx];
        for (paths[first_path_idx + 1 ..]) |this_path| {
            if (this_path.len == 0) continue; // skip empty components
            const prev_sep = prev_path[prev_path.len - 1] == separator;
            const this_sep = this_path[0] == separator;
            if (!prev_sep and !this_sep) {
                try w.writeByte(separator);
            }
            if (prev_sep and this_sep) {
                try w.writeAll(this_path[1..]); // skip redundant separator
            } else {
                try w.writeAll(this_path);
            }
            prev_path = this_path;
        }
    }
};

pub fn join(allocator: std.mem.Allocator, paths: []const []const u8, separator: u8) ![]u8 {
    // Find first non-empty path index.
    const first_path_index = blk: {
        for (paths, 0..) |path, index| {
            if (path.len == 0) continue else break :blk index;
        }

        // All paths provided were empty, so return early.
        return &[0]u8{};
    };

    // Calculate length needed for resulting joined path buffer.
    const total_len = blk: {
        var sum: usize = paths[first_path_index].len;
        var prev_path = paths[first_path_index];
        std.debug.assert(prev_path.len > 0);
        var i: usize = first_path_index + 1;
        while (i < paths.len) : (i += 1) {
            const this_path = paths[i];
            if (this_path.len == 0) continue;
            const prev_sep = prev_path[prev_path.len - 1] == separator;
            const this_sep = this_path[0] == separator;
            sum += @intFromBool(!prev_sep and !this_sep);
            sum += if (prev_sep and this_sep) this_path.len - 1 else this_path.len;
            prev_path = this_path;
        }

        break :blk sum;
    };

    const buf = try allocator.alloc(u8, total_len);
    errdefer allocator.free(buf);

    @memcpy(buf[0..paths[first_path_index].len], paths[first_path_index]);
    var buf_index: usize = paths[first_path_index].len;
    var prev_path = paths[first_path_index];
    std.debug.assert(prev_path.len > 0);
    var i: usize = first_path_index + 1;
    while (i < paths.len) : (i += 1) {
        const this_path = paths[i];
        if (this_path.len == 0) continue;
        const prev_sep = prev_path[prev_path.len - 1] == separator;
        const this_sep = this_path[0] == separator;
        if (!prev_sep and !this_sep) {
            buf[buf_index] = separator;
            buf_index += 1;
        }
        const adjusted_path = if (prev_sep and this_sep) this_path[1..] else this_path;
        @memcpy(buf[buf_index..][0..adjusted_path.len], adjusted_path);
        buf_index += adjusted_path.len;
        prev_path = this_path;
    }

    // No need for shrink since buf is exactly the correct size.
    return buf;
}

//NOTE: this must be kept in sync with SuperMD
pub const PathValidationOptions = struct { empty: bool = false };
pub fn validatePathMessage(
    path: []const u8,
    // Toggle checks
    options: PathValidationOptions,
) ?[]const u8 {
    validatePath(path, options) catch |err| return switch (err) {
        error.Spaces => "remove whitespace surrounding path",
        error.Empty => "this builtin does not accept empty paths",
        error.AbsolutePath => "absolute paths are not allowed here",
        error.Backslash => "use '/' instead of '\\' as the path component separator",
        error.Dots => "'.' and '..' are not allowed",
        error.EmptyComponent => "empty component in path",
    };

    return null;
}

//NOTE: this must be kept in sync with SuperMD
pub fn validatePath(
    path: []const u8,
    // Toggle checks
    options: PathValidationOptions,
) !void {
    // Paths must not have spaces around them
    const spaces = std.mem.trim(u8, path, &std.ascii.whitespace);
    if (spaces.len != path.len) return error.Spaces;

    // Paths cannot be empty unless we allow it
    if (path.len == 0 and options.empty) return;
    if (path.len == 0) return error.Empty;

    // All paths must be relative
    if (path[0] == '/') return error.AbsolutePath;

    // Paths cannot contain Windows-style separators
    if (std.mem.indexOfScalar(u8, path, '\\') != null) return error.Backslash;

    // Path cannot contain any relative component (. or ..)
    var it = std.mem.splitScalar(u8, path, '/');
    while (it.next()) |c| {
        if (std.mem.eql(u8, c, ".") or
            std.mem.eql(u8, c, "..")) return error.Dots;

        if (c.len == 0) {
            if (it.next() != null) return error.EmptyComponent;
        }
    }
}
