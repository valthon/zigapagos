/// How many pruned assets `reportPrunedSiteAssets` names before it stops.
/// A site can legitimately have a large `assets/` tree of which only a handful
/// is linked; naming all of it would bury the build log and make the warning
/// something people learn to ignore, which is the failure mode issue #54 is
/// already about. The total is always reported, so nothing is hidden.
const pruned_assets_listed = 10;

/// Issue #54: report the site assets that were NOT installed because nothing
/// referenced them.
///
/// The pruning itself is correct and stays — an SSG that copied every byte of
/// `assets/` into the output whether or not the site uses it would be a worse
/// tool. What cost a real debugging session was that it happened in complete
/// silence: a hand-authored SVG vanished from the build when a change removed
/// its last `.link()`, and finding out why meant reading the refcount logic in
/// this file.
///
/// A warning rather than an error, because "an asset in the tree that nothing
/// links yet" is a legitimate state (a file staged ahead of the page that will
/// use it). The message names both fixes because which one is right depends on
/// intent: `.link()` it from a template if the site should reference it, or
/// list it in `static_assets` if something outside the build fetches it.
///
/// Deterministic output: `site_assets` is a hash map, so as-found order varies
/// between two otherwise-identical builds. The listed paths are sorted, the
/// same reason `spa.zig`'s `spaHeadWarningAsset` picks the lexicographically
/// smallest match rather than the first one found.
///
/// Four things suppress it, all for the same reason — a warning that fires on
/// correct code is a warning people stop reading:
///   * a failed render pass (`any_rendering_error`), whose refcounts are
///     incomplete by construction;
///   * `assets_dir_path` doubling as a content dir, where every page source is
///     also a site asset;
///   * `.keep`/`.gitkeep` placeholders;
///   * assets consumed by a build-time read builtin (`Build.site_asset_reads`).
/// The incremental fast path is excluded too, but by the early return in
/// `run()` rather than here.
///
/// Allocator contract: self-freeing (NO_SLOP §2.2a contract 1). Everything it
/// allocates is freed before it returns; nothing escapes.
fn reportPrunedSiteAssets(gpa: Allocator, build: *const Build) void {
    // A build whose render pass produced errors has NOT derived a trustworthy
    // set of refcounts: `worker.zig` marks a failed page and moves on, so
    // every asset whose only `.link()` lived on a page that died looks
    // unreferenced here. `run()` does not stop at a render error — it carries
    // on through the install pass to this call, and only `cli/release.zig`
    // checks `any_rendering_error` after `run()` returns — so the gate has to
    // be here. Same fail-closed reasoning as `writeIslandManifest` below.
    if (build.any_rendering_error.load(.acquire)) return;

    if (assetsDirIsContentDir(build.cfg)) return;

    var pruned: std.ArrayListUnmanaged([]const u8) = .empty;
    defer {
        for (pruned.items) |s| gpa.free(s);
        pruned.deinit(gpa);
    }

    var buf: [std.fs.max_path_bytes]u8 = undefined;
    var it = build.site_assets.iterator();
    while (it.next()) |entry| {
        if (entry.value_ptr.raw > 0) continue;
        // Read but not installed is a CORRECT outcome, not a pruning: an
        // asset consumed through `.bytes()`/`.size()`/`.sriHash()`/`.ziggy()`
        // is inlined into the page at build time and has no business in the
        // output tree. Reporting it would tell the author to `.link()` it or
        // add it to `static_assets` — the latter publishing what may well be
        // a private data file. See `Build.site_asset_reads`.
        if (build.site_asset_reads.getPtr(entry.key_ptr.*)) |reads| {
            if (reads.raw > 0) continue;
        }
        if (isDirectoryPlaceholder(entry.key_ptr.name.slice(&build.st))) continue;
        const path = std.fmt.bufPrint(&buf, "{f}", .{
            entry.key_ptr.fmt(&build.st, &build.pt, null, "/"),
        }) catch continue;
        // A failed dup only costs this one line of the report, so drop the
        // entry rather than aborting a build that has otherwise succeeded.
        const owned = gpa.dupe(u8, path) catch continue;
        pruned.append(gpa, owned) catch {
            gpa.free(owned);
            continue;
        };
    }

    if (pruned.items.len == 0) return;

    std.mem.sort([]const u8, pruned.items, {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.lessThan(u8, a, b);
        }
    }.lessThan);

    const shown = @min(pruned.items.len, pruned_assets_listed);
    std.debug.print(
        "warning: {d} asset(s) under '{s}' were not installed because nothing " ++
            "references them. Link one from a template or a content file " ++
            "($site.asset('...').link()), or list it in `static_assets` in " ++
            "zigapagos.ziggy if something outside the build fetches it at a " ++
            "fixed path:\n",
        .{ pruned.items.len, build.cfg.getAssetsDirPath() },
    );
    for (pruned.items[0..shown]) |path| {
        std.debug.print("  - {s}\n", .{path});
    }
    if (pruned.items.len > shown) {
        std.debug.print(
            "  ... and {d} more\n",
            .{pruned.items.len - shown},
        );
    }
}

/// Install every referenced (rc > 0) build asset into the output tree. Runs on
/// BOTH the full and the incremental disk paths: an island-source
/// incremental rebuild must reinstall the freshly rebundled
/// `islands/<name>.js` (an `install_always` asset, rc'd from the start), and
/// `updateFile` is a cheap stat-compare no-op for unchanged files.
/// Allocator contract: `gpa` is used only by the optional `--summary`
/// collector, which owns what it stores (NO_SLOP.md §2.2a contract 2) and is
/// freed by its owner in `run`; this function allocates nothing of its own.
fn installBuildAssets(
    io: Io,
    gpa: Allocator,
    build: *const Build,
    collect: ?*BuildSummary,
) error{OutOfMemory}!void {
    for (build.build_assets.values()) |ba| {
        // Avoid installing if already rc'd
        if (ba.rc.load(.acquire) > 0) {
            // A build asset with no install path is a legitimate config (read
            // via `.bytes()`/`.size()`/… only). Referencing such an asset with
            // `.link()` reports a graceful page error but should never reach
            // here; skip defensively rather than unwrapping a null optional,
            // mirroring the sibling install loops (spa.zig, serve.zig).
            const install_rel = std.mem.trimStart(u8, ba.install_path orelse continue, "/");
            if (collect) |sm| try sm.add(gpa, .build_asset, install_rel);
            _ = build.base_dir.updateFile(
                io,
                ba.input_path,
                build.mode.disk.output_dir,
                install_rel,
                .{},
            ) catch |err| fatal.file(ba.input_path, err);
        }
    }
}

/// Write (or refresh) the dev-only island-usage manifest at `path`
/// from the usage pairs the render workers collected this build. Fail-closed
/// everywhere: a partial render (any_rendering_error), an unreadable/stale old
/// manifest on an incremental build, or a write failure all DELETE the
/// manifest instead — a missing manifest just means the dev loop falls back to
/// a full rebuild, never wrong output. Never fails the build.
fn writeIslandManifest(
    io: Io,
    gpa: Allocator,
    build: *const Build,
    path: []const u8,
    incremental: bool,
    changed_set: *const std.StringHashMapUnmanaged(void),
) void {
    const manifest = @import("islands/manifest.zig");
    if (build.any_rendering_error.load(.acquire)) {
        // Partial render ⇒ the collected usage can't be trusted.
        Io.Dir.cwd().deleteFile(io, path) catch {};
        return;
    }

    var arena_state = std.heap.ArenaAllocator.init(gpa);
    defer arena_state.deinit();
    // `manifest.parse`/`assemble` are contract 4 (NO_SLOP.md §2.2a): they build
    // interlinked graphs with no `deinit`, reclaimed only when this pass's arena
    // drops. `RenderArena` is what says so in their signatures.
    const arena = RenderArena.from(&arena_state);

    // On an incremental build only the changed pages re-derived their mounts;
    // merge into the previous manifest (whose entries for those pages are
    // replaced). Any read/parse failure ⇒ delete (fail closed).
    var old_storage: manifest.Json = undefined;
    var old_ptr: ?*const manifest.Json = null;
    if (incremental) {
        const text = Io.Dir.cwd().readFileAlloc(io, path, arena.a, .limited(16 * 1024 * 1024)) catch {
            Io.Dir.cwd().deleteFile(io, path) catch {};
            return;
        };
        old_storage = manifest.parse(arena, text) catch {
            Io.Dir.cwd().deleteFile(io, path) catch {};
            return;
        };
        old_ptr = &old_storage;
    }

    var assembled = manifest.assemble(
        arena,
        old_ptr,
        changed_set,
        build.island_page_usage.items,
    ) catch fatal.oom();
    // `render` is contract 1 — it frees its own scratch, so it takes the plain
    // allocator (the arena's, here: the bytes are handed straight to the writer
    // below and die with the pass).
    const rendered = manifest.render(arena.a, &assembled) catch fatal.oom();

    writeIslandManifestFile(io, path, rendered) catch |err| {
        log.warn("failed to write the dev island manifest '{s}': {s}", .{
            path, @errorName(err),
        });
        Io.Dir.cwd().deleteFile(io, path) catch {};
    };
}

/// The io half of `writeIslandManifest` (pattern: `src/spa.zig`'s `writeFile`).
/// The parent directory (the dev loop's persistent data dir) already exists.
fn writeIslandManifestFile(io: Io, path: []const u8, contents: []const u8) !void {
    var f = try Io.Dir.cwd().createFile(io, path, .{});
    defer f.close(io);
    var fw = f.writer(io, &.{});
    try fw.interface.writeAll(contents);
}

/// Whether a site asset should be minified rather than copied
/// verbatim on install. True only for `.css` (case-insensitive) when both a
/// Bun path and the CSS minify driver were threaded — i.e. a release build.
/// The in-memory live server never sets `css_minify_driver`, so its CSS is
/// always copied verbatim (readable dev output).
fn shouldMinifyCss(path: []const u8, options: Options) bool {
    if (options.bun_path == null or options.css_minify_driver == null) return false;
    return std.ascii.endsWithIgnoreCase(path, ".css");
}

/// Minify one `.css` site asset by shelling out to the Bun CSS driver
/// (`runtime/sidecar/minify-css.ts`), reading `src_rel` from `src_dir` and
/// writing the minified result to `dest_rel` under `install_dir`. Mirrors the
/// island/SPA JS minify pass; on any failure it exits loudly (fatal) with the
/// offending file named — matching the JS bundling path's fail-the-build
/// behavior. Bun's own diagnostics reach the build log via inherited stderr.
fn installMinifiedCss(
    io: Io,
    gpa: Allocator,
    src_dir: Io.Dir,
    install_dir: Io.Dir,
    src_rel: []const u8,
    dest_rel: []const u8,
    bun_path: []const u8,
    driver: []const u8,
) void {
    // Absolute source path (the CSS file exists, so realPathFile resolves it).
    var src_buf: [std.fs.max_path_bytes]u8 = undefined;
    const src_n = src_dir.realPathFile(io, src_rel, &src_buf) catch |err|
        fatal.file(src_rel, err);
    const src_abs = src_buf[0..src_n];

    // Absolute destination path: realpath the install dir (it exists) and join
    // the relative dest under it. Bun.write creates any missing parent dirs.
    var dir_buf: [std.fs.max_path_bytes]u8 = undefined;
    const dir_n = install_dir.realPathFile(io, ".", &dir_buf) catch |err|
        fatal.file(dest_rel, err);
    const dest_abs = std.fs.path.join(gpa, &.{ dir_buf[0..dir_n], dest_rel }) catch
        fatal.oom();
    defer gpa.free(dest_abs);

    var child = std.process.spawn(io, .{
        .argv = &.{ bun_path, driver, src_abs, dest_abs },
        .stderr = .inherit, // surface Bun's CSS diagnostics in the build log
    }) catch |err| fatal.msg(
        "error: failed to spawn CSS minifier ({s} {s}) for '{s}': {s}\n" ++
            "note: ensure Bun is installed and on PATH (or pass --bun=PATH)\n",
        .{ bun_path, driver, src_rel, @errorName(err) },
    );

    const term = child.wait(io) catch |err| fatal.msg(
        "error: CSS minifier for '{s}' failed: {s}\n",
        .{ src_rel, @errorName(err) },
    );

    switch (term) {
        .exited => |code| if (code != 0) fatal.msg(
            "error: CSS minification of '{s}' failed (bun exit {d}); " ++
                "fix the stylesheet (see the error above) or remove it from the assets dir\n",
            .{ src_rel, code },
        ),
        else => fatal.msg(
            "error: CSS minifier for '{s}' terminated abnormally\n",
            .{src_rel},
        ),
    }
}

